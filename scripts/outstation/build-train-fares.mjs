#!/usr/bin/env node
/**
 * Rebuilds src/lib/outstation/train-fares-data.ts from a fare sweep of the Egyptian National Railways
 * booking site (obs.enr.gov.eg) — the JSON the sweep saves: { date, rows: [[fromEn, fromAr, toEn, toAr,
 * train, departs, arrives, minutes, km, ac2Piastres, ...]] }.
 *
 *   node scripts/outstation/build-train-fares.mjs <sweep.json>
 *
 * Keeps, per ordered station pair, the LOWEST second-class AC (ثانية مكيفة) fare in whole pounds —
 * the owner's rule for a "No ticket" trip (2026-11-07). The site sends piastres.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { refuseUnknownFlags } from "../lib/refuse-arguments.mjs";

// A flag this script does not know is refused, never ignored (scripts/lib/refuse-arguments.mjs).
refuseUnknownFlags({
  name: "build-train-fares",
  entry: import.meta.url,
  known: [],
});

// Station positions (WGS84). The site's own stations carry no coordinates, so these are the stations'
// towns; "Upper Egypt" is the Bashtil terminal (6 km from Ramses), Kalabsha the halt between Idfu and Kom Ombo.
const STATIONS = {
  "ABU TISHT": [26.1236, 32.095], ALEXANDRIA: [31.1925, 29.9047], ASWAN: [24.0995, 32.9015], ASYUT: [27.1801, 31.1837],
  BANHA: [30.4598, 31.1784], "BANI MAZAR": [28.5036, 30.8001], "BENI SUEF": [29.0661, 31.0994],
  "BIRKAT EL-SABA": [30.6286, 31.077], CAIRO: [30.0626, 31.2467], DAMIETTA: [31.4165, 31.8133], DAMNHOUR: [31.0341, 30.4682],
  DARAW: [24.4206, 32.9306], "EL-BALYANA": [26.2364, 32.0028], "EL-GIZA": [30.0103, 31.2071], "EL-MARAGHA": [26.6997, 31.6],
  "EL-MINIA": [28.0896, 30.7565], "EL-MNSOURA": [31.0435, 31.372], "EL-ZQAZYQ": [30.5877, 31.5021], GIRGA: [26.3383, 31.8916],
  IDFU: [24.9781, 32.8755], ISNA: [25.2934, 32.554], "ITAI EL-BARUD": [30.8853, 30.667], "KAFR EL-ZAIAT": [30.8247, 30.815],
  KLABSHA: [24.62, 32.93], "KOM OMBO": [24.4767, 32.9466], LUXOR: [25.6943, 32.6455], MALLAWI: [27.7311, 30.8417],
  "MNYH ALQMH": [30.5164, 31.35], "NAG HAMMADI": [26.0494, 32.2414], "PORT SAID": [31.2565, 32.2841], QENA: [26.1551, 32.716],
  QUESNA: [30.5634, 31.1453], QUS: [25.9134, 32.7631], "SIDI GABER": [31.2186, 29.942], SOHAG: [26.5591, 31.6948],
  TAHTA: [26.7693, 31.5021], TANTA: [30.7865, 31.0004], TEMA: [26.9078, 31.4239], "UPPER EGYPT": [30.072, 31.186],
};
// English names as the employee reads them; the site's own spellings stay the keys.
const DISPLAY = {
  "EL-ZQAZYQ": "Zagazig", "MNYH ALQMH": "Minya al-Qamh", DAMNHOUR: "Damanhour", "EL-MNSOURA": "Mansoura",
  KLABSHA: "Kalabsha", "UPPER EGYPT": "Upper Egypt (Bashtil)", "EL-MINIA": "Minya", "EL-GIZA": "Giza",
};
const title = (s) => DISPLAY[s] ?? s.toLowerCase().replace(/(^|[\s-])([a-z])/g, (m) => m.toUpperCase());

const src = process.argv[2];
if (!src) throw new Error("usage: node scripts/outstation/build-train-fares.mjs <sweep.json>");
const sweep = JSON.parse(readFileSync(src, "utf8"));
const names = Object.keys(STATIONS).sort();
const arabic = {};
const lowest = new Map();
for (const r of sweep.rows) {
  arabic[r[0]] = r[1];
  arabic[r[2]] = r[3];
  if (r[9] == null) continue;
  if (!(r[0] in STATIONS) || !(r[2] in STATIONS)) throw new Error(`station without a position: ${r[0]} or ${r[2]}`);
  const key = `${r[0]}>${r[2]}`;
  const pounds = r[9] / 100;
  if (!lowest.has(key) || pounds < lowest.get(key)) lowest.set(key, pounds);
}
const index = Object.fromEntries(names.map((n, i) => [n, i]));
const fares = [...lowest.entries()]
  .map(([k, v]) => { const [a, b] = k.split(">"); return [index[a], index[b], v]; })
  .sort((x, y) => x[0] - y[0] || x[1] - y[1]);

const out = `// GENERATED by scripts/outstation/build-train-fares.mjs from the railway fare sweep of ${sweep.date}.
// Do not edit by hand — re-run the script on a new sweep.
/* eslint-disable */

export const TRAIN_FARES_COLLECTED_FOR = ${JSON.stringify(sweep.date)};

/** [site name, English name, Arabic name, latitude, longitude] — index = position in this list. */
export const TRAIN_STATIONS: ReadonlyArray<readonly [string, string, string, number, number]> = [
${names.map((n) => `  [${JSON.stringify(n)}, ${JSON.stringify(title(n))}, ${JSON.stringify(arabic[n] ?? "")}, ${STATIONS[n][0]}, ${STATIONS[n][1]}],`).join("\n")}
];

/** [from station index, to station index, lowest second-class AC fare in EGP] — direct trains only. */
export const TRAIN_AC2_LOWEST_FARES: ReadonlyArray<readonly [number, number, number]> = [
${fares.map((f) => `  [${f.join(", ")}],`).join("\n")}
];
`;
const target = join(dirname(fileURLToPath(import.meta.url)), "../../src/lib/outstation/train-fares-data.ts");
writeFileSync(target, out);
console.log(`stations ${names.length}, routes with an AC 2 fare ${fares.length} -> ${target}`);
