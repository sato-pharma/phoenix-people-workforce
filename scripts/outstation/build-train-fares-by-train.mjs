#!/usr/bin/env node
/**
 * Rebuilds src/lib/outstation/train-fares-by-train-data.ts from a fare sweep of the Egyptian National
 * Railways booking site (the JSON sweep-train-fares.mjs saves): every direct train's second-class AC
 * (ثانية مكيفة) fare, per ordered station pair.
 *
 *   node scripts/outstation/build-train-fares-by-train.mjs <sweep.json>
 *
 * The District Manager's train cap reads it (train-fare-cap.ts, owner 28 Nov 2026): a ticket is paid up to
 * the AC 2 fare of the train taken, and one route's trains differ (Cairo → Asyut 210, 250, 290 or 350).
 * It leaves train-fares-data.ts — the No ticket trip's fixed LOWEST fare — exactly as it is.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { refuseUnknownFlags } from "../lib/refuse-arguments.mjs";

// A flag this script does not know is refused, never ignored (scripts/lib/refuse-arguments.mjs).
refuseUnknownFlags({ name: "build-train-fares-by-train", entry: import.meta.url, known: [] });

const src = process.argv[2];
if (!src) throw new Error("usage: node scripts/outstation/build-train-fares-by-train.mjs <sweep.json>");
const sweep = JSON.parse(readFileSync(src, "utf8"));

/** "from>to" → train → highest AC 2 fare in pounds (the site sends piastres). */
const pairs = new Map();
const stations = new Set();
for (const r of sweep.rows) {
  if (r[9] == null) continue;
  const train = String(r[4] ?? "").replace(/[^0-9]/g, "").replace(/^0+(?=.)/, "");
  if (!train) continue;
  stations.add(r[0]);
  stations.add(r[2]);
  const key = `${r[0]}>${r[2]}`;
  const trains = pairs.get(key) ?? new Map();
  trains.set(train, Math.max(r[9] / 100, trains.get(train) ?? 0));
  pairs.set(key, trains);
}
const names = [...stations].sort();
const index = Object.fromEntries(names.map((n, i) => [n, i]));
const rows = [...pairs.entries()]
  .map(([k, trains]) => {
    const [a, b] = k.split(">");
    const packed = [...trains.entries()]
      .sort((x, y) => Number(x[0]) - Number(y[0]))
      .map(([train, fare]) => `${train}=${fare}`)
      .join(",");
    return [index[a], index[b], packed];
  })
  .sort((x, y) => x[0] - y[0] || x[1] - y[1]);

const out = `// GENERATED by scripts/outstation/build-train-fares-by-train.mjs from the railway fare sweep of ${sweep.date}.
// Do not edit by hand — re-run the script on a new sweep.
/* eslint-disable */

export const TRAIN_AC2_BY_TRAIN_COLLECTED_FOR = ${JSON.stringify(sweep.date)};

/** The railway site's station names — index = position in this list (matched to TRAIN_STATIONS by name). */
export const TRAIN_AC2_BY_TRAIN_STATIONS: ReadonlyArray<string> = ${JSON.stringify(names)};

/** [from station index, to station index, "train=AC 2 fare in EGP,…"] — direct trains only. */
export const TRAIN_AC2_BY_TRAIN: ReadonlyArray<readonly [number, number, string]> = [
${rows.map((r) => `  [${r[0]}, ${r[1]}, ${JSON.stringify(r[2])}],`).join("\n")}
];
`;
const target = join(dirname(fileURLToPath(import.meta.url)), "../../src/lib/outstation/train-fares-by-train-data.ts");
writeFileSync(target, out);
const trains = rows.reduce((sum, r) => sum + r[2].split(",").length, 0);
console.log(`stations ${names.length}, routes ${rows.length}, train fares ${trains} -> ${target}`);
