// Regenerates src/lib/format/cairo-zone-transitions.ts from THIS machine's IANA timezone data.
//
// WHY THIS TABLE EXISTS AT ALL. Rendering an instant in Africa/Cairo asks the engine what Egypt's
// UTC offset was at that moment, and the engine answers from the timezone data it happened to be
// built with. Egypt abolished daylight saving in 2014 and brought it back in 2023, so any browser
// built between those dates is an hour out for roughly half of every year — and half this app's
// Cairo timestamps are rendered inside "use client" components, which means Node renders the text
// and the browser renders it again on hydrate. One digit apart is React hydration error #418.
//
// Measured in production, 2026-09-11: one District Sales Manager on Samsung Internet 20
// (Chrome 106, built September 2022) produced every remaining #418 on the platform, on the two
// pages she uses. Her engine thinks Cairo is UTC+2 in September; the server knows it is UTC+3.
//
// So the offset ships WITH THE CODE, exactly like the month names next door in cairo-datetime.ts,
// and the formatter asks this table rather than the reader's browser. Same input, same bytes, on
// every engine ever built.
//
// Run:  node scripts/generate-cairo-zone-transitions.mjs
// Do it on an up-to-date Node — the table is only as current as the tzdata that produced it.

import { writeFileSync } from "node:fs";

import { refuseArguments } from "./lib/refuse-arguments.mjs";

// This script takes no arguments, so it says so instead of ignoring one (scripts/lib/refuse-arguments.mjs).
refuseArguments({
  name: "generate-cairo-zone-transitions",
  usage: `generate-cairo-zone-transitions: regenerate src/lib/format/cairo-zone-transitions.ts from
this machine's IANA timezone data.

  node scripts/generate-cairo-zone-transitions.mjs      rewrite the table, then commit the diff
  node scripts/generate-cairo-zone-transitions.mjs -h   this text

It takes no arguments: FROM_YEAR and TO_YEAR are constants at the top of the file.`,
  hints: [
    "FROM_YEAR / TO_YEAR are constants in this file — edit them, do not pass a range",
  ],
});

const ZONE = "Africa/Cairo";
const FROM_YEAR = 2015;
const TO_YEAR = 2040;

const parts = new Intl.DateTimeFormat("en-US", {
  day: "2-digit",
  hour: "2-digit",
  hourCycle: "h23",
  minute: "2-digit",
  month: "2-digit",
  second: "2-digit",
  timeZone: ZONE,
  year: "numeric",
});

/** Minutes Africa/Cairo is AHEAD of UTC at this instant, per the running engine's tzdata. */
function offsetMinutes(date) {
  const read = {};
  for (const part of parts.formatToParts(date)) {
    if (part.type !== "literal") read[part.type] = Number(part.value);
  }
  const asUtc = Date.UTC(read.year, read.month - 1, read.day, read.hour, read.minute, read.second);
  return Math.round((asUtc - date.getTime()) / 60000);
}

const HOUR = 3600000;
const start = Date.UTC(FROM_YEAR, 0, 1);
const end = Date.UTC(TO_YEAR, 11, 31);

// Day-by-day, refining to the hour only on the days the offset actually moves. Egypt's transitions
// land on a local midnight, so an hour is exact; scanning every hour of 25 years is not.
const transitions = [[start, offsetMinutes(new Date(start))]];
for (let day = start + 86400000; day <= end; day += 86400000) {
  const previous = transitions[transitions.length - 1][1];
  const current = offsetMinutes(new Date(day));
  if (current === previous) continue;
  let at = day - 86400000;
  for (let probe = at; probe <= day; probe += HOUR) {
    if (offsetMinutes(new Date(probe)) === current) { at = probe; break; }
  }
  transitions.push([at, current]);
}

const rows = transitions
  .map(([at, offset]) => `  [${at}, ${offset}], // ${new Date(at).toISOString()} -> UTC${offset >= 0 ? "+" : ""}${offset / 60}`)
  .join("\n");

writeFileSync(
  "src/lib/format/cairo-zone-transitions.ts",
  `// GENERATED by scripts/generate-cairo-zone-transitions.mjs — do not edit by hand.
//
// Africa/Cairo's UTC offset, as a table shipped with the code instead of read from the reader's
// browser. See the generator for why, and tests/cairo-zone-offset.test.ts for the check that tells
// you when Egypt has changed the rule and this needs regenerating.
//
// Covers ${FROM_YEAR}-01-01 to ${TO_YEAR}-12-31. Each entry is [instant in epoch milliseconds, minutes ahead of UTC
// from that instant onward].

export const CAIRO_ZONE_TRANSITIONS: readonly (readonly [number, number])[] = [
${rows}
];

/** The window the table actually covers; outside it the nearest known offset is used. */
export const CAIRO_ZONE_TABLE_RANGE = { from: ${start}, to: ${end} } as const;
`,
);

console.log(`wrote ${transitions.length} transitions, ${FROM_YEAR}-${TO_YEAR}`);
for (const [at, offset] of transitions) console.log(" ", new Date(at).toISOString(), "->", offset / 60);
