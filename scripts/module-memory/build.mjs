#!/usr/bin/env node
// Build (or check) module memory: `.claude/rules/<id>.md` for every module, the module directory in
// AGENTS.md §2.2, and docs/module-memory/history.md.
//
//   node scripts/module-memory/build.mjs            write every generated part
//   node scripts/module-memory/build.mjs --check    exit 1 and name every problem; writes nothing
//
// WHAT IS GENERATED AND WHAT IS NOT. In each rules file only the frontmatter (`paths:` from the
// module map), the header and the block between the NOTES markers are generated. The `## Rules`
// section between the RULES markers is hand-written and PRESERVED — that is where a session adds a
// rule it learned in this module, in the same PR as its work. Never hand-edit a generated block:
// the next build rewrites it and `--check` (in the required `validate` job) fails until you do.
//
// WHAT --check REFUSES (each one is a way module memory silently stops working):
//   - a memory note in the mirror that no module, the index or history claims (an ORPHAN)
//   - an assignment to a note that does not exist, or to a bucket that is not a module
//   - a glob that matches no tracked file (a module that can never load)
//   - a rules file over MODULE_FILE_MAX_BYTES, or one whose generated parts are stale
//   - a rules file with no `paths:` (it would load at STARTUP, which is the cost this exists to end)
//   - a module missing from the AGENTS.md directory
// Account: docs/module-memory.md.
import fs from "node:fs";
import path from "node:path";
import { execSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import {
  MODULES, MODULE_IDS, GLOBAL, HISTORY, NOTES_DIR, MODULE_FILE_MAX_BYTES, rulesFileOf, globToRegExp,
} from "./modules.mjs";

import { refuseUnknownFlags } from "../lib/refuse-arguments.mjs";

// A flag this script does not know is refused, never ignored (scripts/lib/refuse-arguments.mjs).
refuseUnknownFlags({
  name: "module-memory/build",
  entry: import.meta.url,
  known: ["--check", "--file-new", "--seed-rules"],
  hints: [
    "--check reads and writes nothing; a bare run rebuilds the module files",
  ],
});

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
export const ASSIGNMENTS_FILE = "scripts/module-memory/assignments.json";
export const HISTORY_FILE = "docs/module-memory/history.md";
const RULES_BEGIN = "<!-- module-memory:rules:begin — hand-written; add this module's rules here -->";
const RULES_END = "<!-- module-memory:rules:end -->";
const NOTES_BEGIN = "<!-- module-memory:notes:begin — generated by scripts/module-memory/build.mjs; do not edit -->";
const NOTES_END = "<!-- module-memory:notes:end -->";
const DIR_BEGIN = "<!-- module-memory:directory:begin — generated by scripts/module-memory/build.mjs -->";
const DIR_END = "<!-- module-memory:directory:end -->";
// The directory TABLE lives in docs/, read on demand; AGENTS.md carries only the pointer between the
// markers above. The table is derivable (`ls .claude/rules/`, each file's own `paths:`) and a session
// never needs it to reach a module — Claude Code auto-loads the matching rules file, and
// module-memory-injector.mjs covers work that opens no file — so 5.4 KB of it was leaving the
// always-loaded share on every single request. Account: docs/module-memory.md, "The module directory".
export const DIRECTORY_DOC = "docs/module-memory.md";
const DOC_DIR_BEGIN = "<!-- module-memory:directory-table:begin — generated by scripts/module-memory/build.mjs -->";
const DOC_DIR_END = "<!-- module-memory:directory-table:end -->";
const INDEX_FILES = new Set(["MEMORY.md", "MEMORY-ARCHIVE.md"]);

// Line endings normalised: a Windows checkout with core.autocrlf hands back CRLF for files git
// stores as LF, and a byte comparison would call every module file "stale" on that laptop alone.
const read = (rel) => fs.readFileSync(path.join(ROOT, rel), "utf8").replace(/\r\n/g, "\n");
const exists = (rel) => fs.existsSync(path.join(ROOT, rel));

/** The note's own description — the line its index pointer is built from. */
export function noteDescription(text) {
  const m = /^description:\s*(.*)$/m.exec(text);
  if (!m) return "";
  let d = m[1].trim();
  if ((d.startsWith('"') && d.endsWith('"')) || (d.startsWith("'") && d.endsWith("'"))) d = d.slice(1, -1);
  return d.replace(/\\"/g, '"').replace(/\s+/g, " ").trim();
}

export function loadNotes() {
  const dir = path.join(ROOT, NOTES_DIR);
  const notes = new Map();
  for (const f of fs.readdirSync(dir)) {
    if (!f.endsWith(".md") || INDEX_FILES.has(f)) continue;
    notes.set(f.slice(0, -3), noteDescription(fs.readFileSync(path.join(dir, f), "utf8")));
  }
  return notes;
}

export function loadAssignments() {
  return JSON.parse(read(ASSIGNMENTS_FILE));
}

function trackedFiles() {
  return execSync("git ls-files", { cwd: ROOT, maxBuffer: 1 << 28 }).toString().split("\n").filter(Boolean);
}

function frontmatter(mod) {
  return ["---", "paths:", ...mod.globs.map((g) => `  - "${g}"`), "---"].join("\n");
}

function header(mod) {
  return [
    `# Module memory — ${mod.title}`,
    "",
    `**Scope:** ${mod.scope}`,
    "",
    "This file is loaded because this session opened a file of this module (or the module-memory hook matched the work to it). **It binds exactly like AGENTS.md.** First the module's rules, then every memory note filed under it: each note line is the cue, and the whole note is `" + NOTES_DIR + "/<name>.md` (identical to the laptop memory folder). **Before acting on a line that bears on your change, open its note.**",
    "",
    "**Keeping it current:** a rule or fact you learn while working in this module goes into **Rules** below, in the same PR as the work. If a rule changed, EDIT its line — never add a second line that contradicts it. The notes block is generated (`node scripts/module-memory/build.mjs`); a new note reaches it through the fold, which runs three times a day — 09:00, 15:00 and 21:00 Cairo (docs/module-memory.md).",
    "",
    "🔴 **A RULE BULLET OVER 1,200 BYTES MUST NAME ITS `docs/` ACCOUNT, or the required `validate` job goes RED** — `tests/agents-long-hooks-cite-docs.test.ts` measures every line starting `- ` inside the Rules block below, and this module file can sit far under its size cap while one bullet is over this limit. **Relocate FIRST, trim second:** write the evidence into a `docs/` file, then cut the bullet to the cue plus that pointer. Trimming first destroys the account while reading as a tidy-up. 🔴 **AND CITING docs/ IS NOT ENOUGH — the same test caps HOW MANY bullets may be over 1,200 at a tenth of all of them, which has about ONE bullet of slack**, so a long bullet reddens `validate` with its pointer in place (2026-10-04: 26 of 263 against a limit of 26.3). The fix is to shorten YOUR OWN long bullet, never to delete anyone's rule.",
    "",
    "🔴 **PUT THE OPERATIVE CLAIM IN THE BULLET'S FIRST `**bold**` SPAN.** A session that never opens this file sees only that one span: `ruleHeadlines()` in `.claude/hooks/module-memory-injector.mjs` takes the FIRST `**…**` match per bullet (`/\\*\\*(.+?)\\*\\*/`) and nothing else, so a boundary, an exception or a date written in a later bold clause of the same bullet does not travel. A first span that states an absolute the rest of the bullet then qualifies is the worst case — it is read as the whole rule. 🔴 **Those spans are also the only thing that grows the pointer, which `tests/module-memory.test.ts` caps at 4,000 bytes (hard cliff 4,500) — a module that passes it is SPLIT, never trimmed** (`phoenix-crm` → `phoenix-crm-approvals`, 2026-10-03).",
  ].join("\n");
}

function notesBlock(mod, assignments, notes) {
  const slugs = Object.keys(assignments).filter((s) => assignments[s] === mod.id).sort();
  const lines = slugs.map((s) => `- \`${s}\` — ${notes.get(s) || "(note missing from the mirror)"}`);
  return [
    NOTES_BEGIN,
    `## Memory notes (${slugs.length})`,
    "",
    ...(lines.length ? lines : ["_No notes filed under this module yet._"]),
    NOTES_END,
  ].join("\n");
}

/** The hand-written rules section of an existing file, or a seed, or an empty one. */
function rulesSection(existing, seed) {
  if (existing) {
    const a = existing.indexOf(RULES_BEGIN);
    const b = existing.indexOf(RULES_END);
    if (a !== -1 && b > a) return existing.slice(a, b + RULES_END.length);
  }
  const body = seed && seed.trim() ? seed.trim() : "_No module rules yet. Add one here, in the PR that teaches it._";
  return [RULES_BEGIN, "## Rules", "", body, RULES_END].join("\n");
}

export function renderModuleFile(mod, assignments, notes, existing, seed) {
  return [frontmatter(mod), "", header(mod), "", rulesSection(existing, seed), "", notesBlock(mod, assignments, notes), ""].join("\n");
}

export function renderHistory(assignments, notes) {
  const slugs = Object.keys(assignments).filter((s) => assignments[s] === HISTORY).sort();
  return [
    "# Module memory — history (never loaded)",
    "",
    "Memory notes about retired platforms (Vercel, Google Cloud Run/GCP, Sentry, the npm era), retired",
    "tools, and areas frozen by the owner. **Nothing here is current guidance — do not act on it.** It is",
    "kept so a question about the past can still be answered. Generated by",
    "`node scripts/module-memory/build.mjs`; the full notes are in `" + NOTES_DIR + "/`.",
    "",
    ...slugs.map((s) => `- \`${s}\` — ${notes.get(s) || "(note missing from the mirror)"}`),
    "",
  ].join("\n");
}

export function renderDirectory() {
  return [
    DIR_BEGIN,
    `**${MODULES.length} modules**, each one a `
      + "`.claude/rules/<id>.md` whose own `paths:` holds every glob. The id → title → globs table is in "
      + `\`${DIRECTORY_DOC}\` ("The module directory"); \`ls .claude/rules/\` lists them. You do not need `
      + "either to reach a module — Claude Code loads the matching file the moment you open one of its "
      + "files, and `.claude/hooks/module-memory-injector.mjs` matches work that opens no file.",
    DIR_END,
  ].join("\n");
}

export function renderDirectoryTable() {
  return [
    DOC_DIR_BEGIN,
    "| Module | Loads when a session touches |",
    "| --- | --- |",
    ...MODULES.map((m) => `| \`${m.id}\` — ${m.title} | \`${m.globs[0]}\` and ${m.globs.length - 1} more |`),
    DOC_DIR_END,
  ].join("\n");
}

const splice = (text, begin, end, body) => {
  const a = text.indexOf(begin);
  const b = text.indexOf(end);
  if (a === -1 || b < a) return null;
  return text.slice(0, a) + body + text.slice(b + end.length);
};

function withDirectory(agents) {
  return splice(agents, DIR_BEGIN, DIR_END, renderDirectory());
}

function withDirectoryTable(doc) {
  return splice(doc, DOC_DIR_BEGIN, DOC_DIR_END, renderDirectoryTable());
}

/** Everything --check verifies. Returns a list of problems (empty = healthy). */
export function checkModuleMemory() {
  const problems = [];
  const notes = loadNotes();
  const assignments = loadAssignments();
  const buckets = new Set([...MODULE_IDS, GLOBAL, HISTORY]);

  for (const [slug, bucket] of Object.entries(assignments)) {
    if (!buckets.has(bucket)) problems.push(`assignment ${slug} -> "${bucket}" is not a module, "${GLOBAL}" or "${HISTORY}"`);
    if (!notes.has(slug)) problems.push(`assignment ${slug} names a note that is not in ${NOTES_DIR}/`);
  }
  for (const slug of notes.keys()) {
    if (!(slug in assignments)) problems.push(`ORPHAN: memory note ${slug} is filed under no module — add it to ${ASSIGNMENTS_FILE} (or run the fold)`);
  }

  const files = trackedFiles();
  for (const mod of MODULES) {
    for (const g of mod.globs) {
      const re = globToRegExp(g);
      if (!files.some((f) => re.test(f))) problems.push(`module ${mod.id}: glob ${g} matches no tracked file — it can never load`);
    }
    const rel = rulesFileOf(mod.id);
    if (!exists(rel)) {
      problems.push(`module ${mod.id}: ${rel} is missing — run node scripts/module-memory/build.mjs`);
      continue;
    }
    const current = read(rel);
    const want = renderModuleFile(mod, assignments, notes, current, null);
    if (current !== want) problems.push(`module ${mod.id}: ${rel} is stale — run node scripts/module-memory/build.mjs`);
    const bytes = Buffer.byteLength(current);
    if (bytes > MODULE_FILE_MAX_BYTES) problems.push(`module ${mod.id}: ${rel} is ${bytes} bytes, over ${MODULE_FILE_MAX_BYTES} — split the module`);
  }

  for (const f of fs.existsSync(path.join(ROOT, ".claude/rules")) ? fs.readdirSync(path.join(ROOT, ".claude/rules")) : []) {
    if (!f.endsWith(".md")) continue;
    const text = read(`.claude/rules/${f}`);
    if (!/^---\r?\n(?:[\s\S]*?\n)?paths:/.test(text)) problems.push(`.claude/rules/${f} has no paths: — it would load at STARTUP for every session`);
    if (!MODULE_IDS.includes(f.slice(0, -3))) problems.push(`.claude/rules/${f} is not a module in scripts/module-memory/modules.mjs`);
  }

  if (!exists(HISTORY_FILE) || read(HISTORY_FILE) !== renderHistory(assignments, notes)) {
    problems.push(`${HISTORY_FILE} is stale — run node scripts/module-memory/build.mjs`);
  }
  const agents = read("AGENTS.md");
  const rebuilt = withDirectory(agents);
  if (rebuilt === null) problems.push("AGENTS.md has no module directory markers (§2.2)");
  else if (rebuilt !== agents) problems.push("AGENTS.md module directory is stale — run node scripts/module-memory/build.mjs");

  if (!exists(DIRECTORY_DOC)) problems.push(`${DIRECTORY_DOC} is missing — it holds the module directory table`);
  else {
    const doc = read(DIRECTORY_DOC);
    const rebuiltDoc = withDirectoryTable(doc);
    if (rebuiltDoc === null) problems.push(`${DIRECTORY_DOC} has no module directory-table markers`);
    else if (rebuiltDoc !== doc) problems.push(`${DIRECTORY_DOC} module directory table is stale — run node scripts/module-memory/build.mjs`);
  }
  return problems;
}

function build(seedDir) {
  const notes = loadNotes();
  const assignments = loadAssignments();
  fs.mkdirSync(path.join(ROOT, ".claude/rules"), { recursive: true });
  const report = [];
  for (const mod of MODULES) {
    const rel = rulesFileOf(mod.id);
    const existing = exists(rel) ? read(rel) : null;
    const seedPath = seedDir ? path.join(seedDir, `${mod.id}.md`) : null;
    const seed = seedPath && fs.existsSync(seedPath) ? fs.readFileSync(seedPath, "utf8") : null;
    const text = renderModuleFile(mod, assignments, notes, existing, seed);
    fs.writeFileSync(path.join(ROOT, rel), text);
    report.push(`${mod.id.padEnd(17)} ${String(Buffer.byteLength(text)).padStart(6)} bytes  ${Object.values(assignments).filter((b) => b === mod.id).length} notes`);
  }
  fs.mkdirSync(path.join(ROOT, path.dirname(HISTORY_FILE)), { recursive: true });
  fs.writeFileSync(path.join(ROOT, HISTORY_FILE), renderHistory(assignments, notes));
  const agents = read("AGENTS.md");
  const rebuilt = withDirectory(agents);
  if (rebuilt !== null && rebuilt !== agents) fs.writeFileSync(path.join(ROOT, "AGENTS.md"), rebuilt);
  const doc = exists(DIRECTORY_DOC) ? read(DIRECTORY_DOC) : null;
  const rebuiltDoc = doc === null ? null : withDirectoryTable(doc);
  if (rebuiltDoc !== null && rebuiltDoc !== doc) fs.writeFileSync(path.join(ROOT, DIRECTORY_DOC), rebuiltDoc);
  console.log(report.join("\n"));
  if (rebuilt === null) console.log("NOTE: AGENTS.md has no module directory markers yet — the directory was not written.");
  if (rebuiltDoc === null) console.log(`NOTE: ${DIRECTORY_DOC} has no module directory-table markers yet — the table was not written.`);
}

/**
 * File every mirrored note no assignment claims (by the fold's classifier) and drop assignments
 * whose note no longer exists. `scripts/sync-cloud-context.mjs` runs this after every mirror
 * refresh, so the mirror and module memory always move together and a refresh can never turn a
 * PR red with an orphan. Returns the counts.
 */
export async function fileNewNotes() {
  const { classify } = await import("./fold.mjs");
  const lib = await import("./modules.mjs");
  const dir = path.join(ROOT, NOTES_DIR);
  const assignments = loadAssignments();
  let filed = 0;
  let dropped = 0;
  for (const f of fs.readdirSync(dir)) {
    if (!f.endsWith(".md") || INDEX_FILES.has(f)) continue;
    const slug = f.slice(0, -3);
    if (slug in assignments) continue;
    const { module, how } = classify(slug, fs.readFileSync(path.join(dir, f), "utf8"), lib);
    assignments[slug] = module;
    filed++;
    console.log(`module memory: filed ${slug} -> ${module} (${how})`);
  }
  for (const slug of Object.keys(assignments)) {
    if (!fs.existsSync(path.join(dir, `${slug}.md`))) { delete assignments[slug]; dropped++; }
  }
  const sorted = Object.fromEntries(Object.keys(assignments).sort().map((k) => [k, assignments[k]]));
  fs.writeFileSync(path.join(ROOT, ASSIGNMENTS_FILE), JSON.stringify(sorted, null, 2) + "\n");
  return { filed, dropped };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes("--file-new")) {
    const { filed, dropped } = await fileNewNotes();
    console.log(`module memory: ${filed} new note(s) filed, ${dropped} vanished note(s) dropped`);
    build(null);
  } else if (process.argv.includes("--check")) {
    const problems = checkModuleMemory();
    if (problems.length) {
      console.error(`module memory: ${problems.length} problem(s)\n- ${problems.join("\n- ")}`);
      process.exit(1);
    }
    console.log("module memory: healthy");
  } else {
    const i = process.argv.indexOf("--seed-rules");
    build(i !== -1 ? process.argv[i + 1] : null);
  }
}
