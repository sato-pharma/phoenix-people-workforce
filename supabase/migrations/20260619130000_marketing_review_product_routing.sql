-- Marketing requests — per-line review routing + Financial Advisor finance step.
--
-- After SFE Validation the reviewer (and which line PM/GPM are CC'd to comment) is chosen by the
-- request's line:
--   Anti Inf -> Marketing Manager reviews; the line Product Manager is CC'd (can comment, no gate).
--   CNS      -> Marketing Manager reviews.
--   Pedia    -> Group Product Manager reviews (Marketing Manager excluded).
--   any other / unmapped line -> Marketing Manager (template default, unchanged).
-- Finance Execution is re-pointed to the new Financial Advisor role (the app falls back to Finance
-- Manager at resolution time until a Financial Advisor account exists, so the chain never stalls).

-- 1) Routing table -------------------------------------------------------------------------------
create table if not exists public.marketing_review_routing (
  id bigint generated by default as identity primary key,
  line_id bigint not null references public.lines (id) on delete cascade,
  reviewer_role text not null,
  cc_roles text[] not null default '{}',
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint marketing_review_routing_role_not_blank check (btrim(reviewer_role) <> '')
);

-- One active routing row per line (the request line is the routing key).
create unique index if not exists marketing_review_routing_active_line_uidx
  on public.marketing_review_routing (line_id)
  where active = true;

alter table public.marketing_review_routing enable row level security;

grant select, insert, update, delete on public.marketing_review_routing to service_role;
grant usage, select on sequence public.marketing_review_routing_id_seq to authenticated, service_role;
grant select on public.marketing_review_routing to authenticated;

drop policy if exists marketing_review_routing_authenticated_read on public.marketing_review_routing;
create policy marketing_review_routing_authenticated_read
on public.marketing_review_routing
for select
to authenticated
using (active = true);

-- 2) Seed the three lines (resolve line ids by name; idempotent) ----------------------------------
insert into public.marketing_review_routing (line_id, reviewer_role, cc_roles)
select l.id, v.reviewer_role, v.cc_roles
from (values
  ('Anti Inf', 'Marketing Manager',      array['Product Manager']::text[]),
  ('CNS',      'Marketing Manager',      array[]::text[]),
  ('Pedia',    'Group Product Manager',  array[]::text[])
) as v(line_name, reviewer_role, cc_roles)
join public.lines l on l.name = v.line_name
where not exists (
  select 1 from public.marketing_review_routing r where r.line_id = l.id and r.active
);

-- 3) Re-point Finance Execution to the Financial Advisor role -------------------------------------
update public.marketing_workflow_steps
set assigned_role = 'Financial Advisor', updated_at = now()
where step_code = 'finance_execution';

comment on table public.marketing_review_routing is
  'Per-line override for the post-SFE Marketing Review reviewer + the line roles CC''d to comment. Unmapped lines fall back to the Marketing Manager template step.';
