-- ─────────────────────────────────────────────────────────────────────────────
-- 8. Prove it, rather than report success and hope
-- ─────────────────────────────────────────────────────────────────────────────

do $verify$
declare
  missing text[];
  t text;
  type_count integer;
  step_count integer;
  rls_off text[];
  conference_active boolean;
begin
  missing := array[]::text[];
  rls_off := array[]::text[];

  foreach t in array array[
    'market_awareness_activity_types',
    'market_awareness_activities',
    'market_awareness_activity_lines',
    'market_awareness_activity_products',
    'market_awareness_activity_bricks',
    'market_awareness_cost_items',
    'market_awareness_workflow_steps',
    'market_awareness_decisions',
    'market_awareness_evidence'
  ] loop
    -- pg_class, not a ledger. A migration file written is not a migration applied, and
    -- list_migrations reports the ledger rather than reality.
    if not exists (
      select 1 from pg_class c
      join pg_namespace n on n.oid = c.relnamespace
      where n.nspname = 'public' and c.relname = t and c.relkind = 'r'
    ) then
      missing := missing || t;
    elsif not exists (
      select 1 from pg_class c
      join pg_namespace n on n.oid = c.relnamespace
      where n.nspname = 'public' and c.relname = t and c.relrowsecurity
    ) then
      rls_off := rls_off || t;
    end if;
  end loop;

  if array_length(missing, 1) is not null then
    raise exception 'market awareness: tables missing after migration: %', missing;
  end if;
  if array_length(rls_off, 1) is not null then
    raise exception 'market awareness: RLS not enabled on: %', rls_off;
  end if;

  select count(*) into type_count from public.market_awareness_activity_types where active;
  if type_count <> 7 then
    raise exception 'market awareness: expected 7 active activity types, found %', type_count;
  end if;

  select count(*) into step_count from public.market_awareness_workflow_steps where active;
  if step_count <> 2 then
    raise exception 'market awareness: expected 2 active workflow steps, found %', step_count;
  end if;

  select active into conference_active
    from public.marketing_request_types where code = 'conference';
  if conference_active then
    raise exception 'market awareness: marketing request type conference is still active';
  end if;

  raise notice 'market awareness: 9 tables, RLS on all, % types, % steps, conference retired',
    type_count, step_count;
end;
$verify$;
