-- ─────────────────────────────────────────────────────────────────────────────
-- 6. RLS from the first day
-- ─────────────────────────────────────────────────────────────────────────────
--
-- Visibility in this app is APPLICATION-scoped: the routes use the service-role client and enforce
-- with assertPermission. RLS here is the backstop that keeps a browser-side anon or authenticated
-- key from reading the table directly. A table created in `public` inherits the schema-wide grants,
-- so the REVOKE is what actually shuts it and the GRANT back to service_role is not optional —
-- REVOKE FROM PUBLIC strips what service_role held implicitly through the default ACL.

do $rls$
declare
  t text;
begin
  foreach t in array array[
    'market_awareness_activity_types',
    'market_awareness_activities',
    'market_awareness_activity_lines',
    'market_awareness_activity_products',
    'market_awareness_activity_bricks',
    'market_awareness_cost_items',
    'market_awareness_workflow_steps',
    'market_awareness_decisions',
    'market_awareness_evidence'
  ] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists %I on public.%I', t || '_service_role_all', t);
    execute format(
      'create policy %I on public.%I for all to service_role using (true) with check (true)',
      t || '_service_role_all', t
    );
    execute format('revoke all on table public.%I from anon', t);
    execute format('revoke all on table public.%I from authenticated', t);
    execute format('revoke all on table public.%I from public', t);
    execute format('grant all on table public.%I to service_role', t);
  end loop;
end;
$rls$;

