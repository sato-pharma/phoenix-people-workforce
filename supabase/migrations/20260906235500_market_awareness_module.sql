-- Market Awareness — a Group Product Manager / Product Manager module for awareness activities.
--
-- WHY THIS IS NOT A MARKETING REQUEST TYPE. `marketing_requests.customer_id` is NOT NULL: every row
-- there is anchored to exactly one validated customer. An awareness activity is anchored to a PLACE
-- and a PRODUCT SET — a round table has a venue and many doctors, not one customer. The live
-- marketing chain also runs an SFE validation step that exists only because the requester is field
-- force, and these requesters are not. `conference` has existed as marketing request type 5 since
-- launch and has been raised exactly once in the year to 2026-09-06, which is the measured cost of
-- making a product manager invent a customer to hold an event against.
--
-- THREE LINE VOCABULARIES, AND THIS TABLE STORES THE CANONICAL ONE. `public.lines` is the entity
-- (id 1..4, "Anti Infective" / "Pedia" / "CNS" / "Head Office"). `au.line_area_map.line_code` spells
-- the same lines `anti_infective` / `cns` / `pedia`, and `source_of_sales_fact_rollup.official_line`
-- spells them "Anti Infective" / "CNS" / "Pedia". Storing a line as text here would pick one of the
-- three and silently fail to join the other two, so every line reference below is `lines.id` and the
-- two spellings are derived in `src/lib/market-awareness/lines.ts`.
--
-- THE PRIMARY LINE IS LOAD-BEARING, NOT DECORATION. The owner allows several lines per activity
-- (answer 9) but the region map is per line — Anti-Infective spans 9 regions, CNS and Pedia 7 each,
-- over the same 49 areas — so one area sits in a DIFFERENT region depending on the line and there is
-- no single region list to cascade from. `primary_line_id` is the line whose map drives the
-- region -> area -> brick cascade. Owner confirmed 2026-09-06.
--
-- Nothing here stores a sales figure. Tracking is read live from `source_of_sales_fact_rollup` so a
-- closing correction or a price fix flows through, exactly as a price fix already restates every
-- published closing. Freezing a number into the activity would create a second sales truth.

