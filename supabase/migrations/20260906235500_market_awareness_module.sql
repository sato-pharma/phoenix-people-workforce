-- ─────────────────────────────────────────────────────────────────────────────
-- 2. The activity
-- ─────────────────────────────────────────────────────────────────────────────

create table if not exists public.market_awareness_activities (
  id uuid primary key default gen_random_uuid(),
  activity_code text not null unique,
  status text not null default 'draft',

  requester_hr_id text not null,
  -- Resolved at submit from the requester's reporting line, then FROZEN. Reading it live would
  -- re-point a decided step at whoever holds the seat today and rewrite who approved what.
  manager_hr_id text,

  activity_type_id bigint not null references public.market_awareness_activity_types(id),
  title text,
  venue text,
  city text,
  start_date date not null,
  end_date date,
  expected_attendees integer,
  speakers text,

  -- Geography. The primary line drives the cascade; region and area are stored as codes because
  -- that is what au.line_area_map and source_of_sales_fact_rollup both key on.
  primary_line_id bigint not null references public.lines(id),
  region_code text not null,
  area_code text not null,

  -- Money. `amended_cost` is the CEO's own decision when he approves at a different figure; it is
  -- never written by anyone else, and the payable figure is coalesce(amended_cost, estimated_cost).
  currency text not null default 'EGP',
  estimated_cost numeric(14, 2) not null,
  amended_cost numeric(14, 2),
  actual_cost numeric(14, 2),

  -- Measurement window. duration_months is the owner's "duration of expected increase"; baseline
  -- is what it is judged against, because sales went up means nothing without a before.
  duration_months integer not null default 3,
  baseline_months integer not null default 3,
  expected_uplift_pct numeric(6, 2),

  -- Finance is informed and marks paid / not paid. Deliberately NOT the marketing invoice
  -- obligation — no finance hold, no overdue nudge (owner answer 18).
  finance_paid boolean not null default false,
  finance_marked_at timestamptz,
  finance_marked_by_hr_id text,

  -- The seat holders as they were at approval. The SCREEN shows today's holder (owner answer 33),
  -- but detecting "the original rep was replaced" needs the original on record — display is live,
  -- the record is frozen.
  rep_hr_id_at_approval text,
  dm_hr_id_at_approval text,

  executed_at date,
  outcome_note text,

  submitted_at timestamptz,
  approved_at timestamptz,
  rejected_at timestamptz,
  returned_at timestamptz,
  withdrawn_at timestamptz,
  closed_at timestamptz,

  created_by_hr_id text,
  updated_by_hr_id text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint market_awareness_activities_status_check check (status in (
    'draft', 'pending_manager', 'pending_ceo', 'returned', 'rejected',
    'approved', 'executed', 'closed', 'withdrawn'
  )),
  constraint market_awareness_activities_code_not_blank check (btrim(activity_code) <> ''),
  constraint market_awareness_activities_region_not_blank check (btrim(region_code) <> ''),
  constraint market_awareness_activities_area_not_blank check (btrim(area_code) <> ''),
  constraint market_awareness_activities_cost_positive check (estimated_cost > 0),
  constraint market_awareness_activities_amended_positive
    check (amended_cost is null or amended_cost > 0),
  constraint market_awareness_activities_actual_positive
    check (actual_cost is null or actual_cost >= 0),
  -- 1 to 12 months, owner answer 22. An unbounded window means an activity is never finished being
  -- measured and the tracking list grows for ever.
  constraint market_awareness_activities_duration_range
    check (duration_months between 1 and 12),
  constraint market_awareness_activities_baseline_range
    check (baseline_months between 1 and 12),
  constraint market_awareness_activities_dates_ordered
    check (end_date is null or end_date >= start_date)
);

create index if not exists market_awareness_activities_requester_idx
  on public.market_awareness_activities (requester_hr_id, created_at desc);
create index if not exists market_awareness_activities_status_idx
  on public.market_awareness_activities (status, created_at desc);
create index if not exists market_awareness_activities_area_idx
