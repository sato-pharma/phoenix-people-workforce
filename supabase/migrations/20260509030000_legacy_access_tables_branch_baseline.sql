    array['job_offers', 'phx_job_offers_service_role'],
    array['lines', 'phx_lines_service_role'],
    array['notification_delivery_logs', 'phx_notification_delivery_logs_service_role'],
    array['notification_events', 'phx_notification_events_service_role'],
    array['notification_outbox', 'phx_notification_outbox_service_role'],
    array['permissions', 'phx_permissions_service_role'],
