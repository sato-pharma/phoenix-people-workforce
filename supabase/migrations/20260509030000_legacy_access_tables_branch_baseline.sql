    array['position_vacancies', 'phx_position_vacancies_service_role'],
    array['positions', 'phx_positions_service_role'],
    array['role_permission_overrides', 'phx_role_permission_overrides_service_role'],
    array['roles', 'phx_roles_service_role'],
    array['system_audit_logs', 'phx_system_audit_logs_service_role'],
    array['teams', 'phx_teams_service_role'],
    array['user_roles', 'phx_user_roles_service_role'],
    array['users', 'phx_users_service_role']
  ]
  loop
    if to_regclass('public.' || item[1]) is not null
       and not exists (
         select 1
         from pg_policies
         where schemaname = 'public'
           and tablename = item[1]
           and policyname = item[2]
       ) then
      execute format(
        'create policy %I on public.%I for all using (true) with check (true)',
        item[2],
        item[1]
      );
    end if;
  end loop;
end $$;

