-- Compatibility baseline for legacy access-control tables and policy names.
-- Early Supabase advisor cleanup migrations alter these objects, but some were
-- created directly in production before the local migration chain existed.

begin;

create table if not exists public.users (
  id uuid primary key default gen_random_uuid(),
  hr_id text null,
  employee_hr_id text null,
  email text null,
  role text null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.roles (
  id bigint generated by default as identity primary key,
  name text unique,
  created_at timestamptz not null default now()
);

create table if not exists public.permissions (
  id bigint generated by default as identity primary key,
  resource text null,
  action text null,
  created_at timestamptz not null default now()
);

create table if not exists public.user_roles (
  id bigint generated by default as identity primary key,
  user_id uuid null,
  role_id bigint null,
  created_at timestamptz not null default now()
);

create table if not exists public.access_scopes (
  id bigint generated by default as identity primary key,
  name text unique,
  created_at timestamptz not null default now()
);

create table if not exists public.role_permission_overrides (
  role_name text not null,
  resource text not null,
  action text not null,
  is_allowed boolean not null default true,
  updated_by text null,
  updated_at timestamptz not null default now(),
  primary key (role_name, resource, action)
);

create table if not exists public.audit_logs (
  id uuid primary key default gen_random_uuid(),
  actor_login_id text null,
  entity_type text null,
  entity_id text null,
  summary text null,
  old_values jsonb null,
  new_values jsonb null,
  created_at timestamptz not null default now()
);

create table if not exists public.employee_documents (
  id uuid primary key default gen_random_uuid(),
  employee_hr_id text null,
  uploaded_by_user_id uuid null,
  file_name text null,
  created_at timestamptz not null default now()
);

create table if not exists public.notification_delivery_logs (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now()
);

create table if not exists public.notification_outbox (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now()
);

create table if not exists public.platform_settings (
  key text primary key,
  value jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.system_audit_logs (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now()
);

alter table public.employee_history
  add column if not exists changed_by_user_id uuid;

alter table public.users enable row level security;
alter table public.roles enable row level security;
alter table public.permissions enable row level security;
alter table public.user_roles enable row level security;
alter table public.access_scopes enable row level security;
alter table public.role_permission_overrides enable row level security;
alter table public.audit_logs enable row level security;
alter table public.employee_documents enable row level security;
alter table public.notification_delivery_logs enable row level security;
alter table public.notification_outbox enable row level security;
alter table public.platform_settings enable row level security;
alter table public.system_audit_logs enable row level security;

