create table if not exists public.attendance_device_user_map (
  id bigint generated by default as identity primary key,
  device_id text not null,
  device_user_id text not null,
  employee_hr_id text not null references public.employees(hr_id) on update cascade on delete cascade,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (device_id, device_user_id)
);

create index if not exists attendance_device_user_map_employee_idx
  on public.attendance_device_user_map (employee_hr_id);

create index if not exists attendance_device_user_map_active_idx
  on public.attendance_device_user_map (device_id, device_user_id)
  where is_active = true;

create table if not exists public.attendance_raw_punches (
  id bigint generated by default as identity primary key,
  device_id text not null,
  device_user_id text not null,
  employee_hr_id text null references public.employees(hr_id) on update cascade on delete set null,
  punch_time timestamptz not null,
  punch_type text null,
  verify_mode text null,
  raw_payload jsonb not null default '{}'::jsonb,
  source_run_id text null,
  ingested_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);

create unique index if not exists attendance_raw_punches_idempotency_typed_idx
  on public.attendance_raw_punches (device_id, device_user_id, punch_time, punch_type)
  where punch_type is not null;

create unique index if not exists attendance_raw_punches_idempotency_null_type_idx
  on public.attendance_raw_punches (device_id, device_user_id, punch_time)
  where punch_type is null;

create index if not exists attendance_raw_punches_employee_time_idx
  on public.attendance_raw_punches (employee_hr_id, punch_time desc);

create index if not exists attendance_raw_punches_device_time_idx
  on public.attendance_raw_punches (device_id, punch_time desc);

create index if not exists attendance_raw_punches_source_run_idx
  on public.attendance_raw_punches (source_run_id)
  where source_run_id is not null;

alter table public.attendance_device_user_map enable row level security;
alter table public.attendance_raw_punches enable row level security;

revoke all on table public.attendance_device_user_map from anon, authenticated;
revoke all on table public.attendance_raw_punches from anon, authenticated;
grant select, insert, update, delete on table public.attendance_device_user_map to service_role;
grant select, insert, update, delete on table public.attendance_raw_punches to service_role;
grant usage, select on sequence public.attendance_device_user_map_id_seq to service_role;
grant usage, select on sequence public.attendance_raw_punches_id_seq to service_role;

drop policy if exists attendance_device_user_map_service_role_all
  on public.attendance_device_user_map;
create policy attendance_device_user_map_service_role_all
  on public.attendance_device_user_map
  for all
  to service_role
  using (true)
  with check (true);

drop policy if exists attendance_raw_punches_service_role_all
  on public.attendance_raw_punches;
create policy attendance_raw_punches_service_role_all
  on public.attendance_raw_punches
  for all
  to service_role
  using (true)
  with check (true);

comment on table public.attendance_device_user_map is
  'Maps fingerprint device user IDs to Phoenix employees.hr_id for direct attendance ingestion.';

comment on table public.attendance_raw_punches is
  'Raw fingerprint attendance punches ingested from a local Windows attendance agent. No payroll or attendance calculations are stored here.';
