insert into public.source_of_sales_regions (
  region_code,
  region_name,
  normalized_region_name,
  source_file,
  source_sheet,
  active,
  updated_at
)
select
  region_code,
  max(region_name) as region_name,
  lower(max(region_name)) as normalized_region_name,
  'Area-Regions codes.xlsx',
  'Regions',
  true,
  now()
from public.source_of_sales_area_regions
where active = true
group by region_code
on conflict (region_code) do update set
  region_name = excluded.region_name,
  normalized_region_name = excluded.normalized_region_name,
  active = true,
  updated_at = now();

insert into public.source_of_sales_areas (
  area_code,
  area_name,
  normalized_area_name,
  region_code,
  region_name,
  source_file,
  source_sheet,
  source_row_number,
  active,
  updated_at
)
select
  area_code,
  area_name,
  normalized_area_name,
  region_code,
  region_name,
  source_file,
  source_sheet,
  source_row_number,
  active,
  now()
from public.source_of_sales_area_regions
on conflict (area_code) do update set
  area_name = excluded.area_name,
  normalized_area_name = excluded.normalized_area_name,
  region_code = excluded.region_code,
  region_name = excluded.region_name,
  source_file = excluded.source_file,
  source_sheet = excluded.source_sheet,
  source_row_number = excluded.source_row_number,
  active = excluded.active,
  updated_at = now();

