create table if not exists public.source_of_sales_regions (
  region_code text primary key,
  region_name text not null,
  normalized_region_name text not null,
  source_file text not null default 'Area-Regions codes.xlsx',
  source_sheet text not null default 'Regions',
  source_row_number integer null,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint source_of_sales_regions_code_not_blank check (btrim(region_code) <> ''),
  constraint source_of_sales_regions_name_not_blank check (btrim(region_name) <> '')
);

