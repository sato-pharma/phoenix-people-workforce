-- Phase 1 / Performance: pre-aggregated rollup of source_of_sales_import_rows.
--
-- The executive / sales-intelligence RPCs (phx_exec_distributor_product, phx_exec_brick,
-- phx_si_period_totals) live-scan the 410 MB raw fact table on every dashboard load
-- (4-13s). These rollups collapse 143k rows to ~20k (and drop the 69 MB raw_row jsonb),
-- so the functions read a small, cache-resident summary instead.
--
-- Pricing stays LIVE: we store effective_units = sum(qty*(1-discount)) and direct_value,
-- NEVER a priced value. The functions multiply effective_units by the CURRENT
-- source_of_sales_products.factory_price at query time, so a price edit is reflected
-- immediately without re-importing.

-- ---------------------------------------------------------------------------
-- Fact rollup: one row per (batch, period, distributor, line, region, area, brick,
-- product, is_direct). is_direct is in the grain so direct/non-direct never mix.
-- ---------------------------------------------------------------------------
create table if not exists public.source_of_sales_fact_rollup (
  id               bigint generated by default as identity primary key,
  batch_id         uuid not null references public.source_of_sales_import_batches(id) on delete cascade,
  period           text not null,
  distributor_code text,
  official_line    text,
  region_code      text,
  area_code        text,
  brick_id         text,
  product_code     text,
  product_name     text,
  is_direct        boolean not null default false,
  effective_units  numeric(20,6) not null default 0,   -- sum(qty*(1-coalesce(discount,0))) -> pricing base
  total_qty        numeric(20,6) not null default 0,   -- sum(qty) -> "units" output
  total_bonus_qty  numeric(20,6) not null default 0,
  direct_value     numeric(20,6) not null default 0,   -- sum(value) where is_direct (stored Direct truth)
  row_count        integer not null default 0,
  created_at       timestamptz not null default now()
);

-- Grain uniqueness. NULLS NOT DISTINCT so a NULL grain value collates as a single
-- group (matching SQL GROUP BY semantics in the refresh), while '' stays distinct.
create unique index if not exists source_of_sales_fact_rollup_grain_uniq
  on public.source_of_sales_fact_rollup
  (batch_id, distributor_code, official_line, region_code, area_code, brick_id, product_code, is_direct)
  nulls not distinct;

create index if not exists source_of_sales_fact_rollup_period_idx
  on public.source_of_sales_fact_rollup (period);

create index if not exists source_of_sales_fact_rollup_batch_idx
  on public.source_of_sales_fact_rollup (batch_id);

-- ---------------------------------------------------------------------------
-- Customer-presence rollup: customer_count needs distinct client_code, which a
-- pre-SUM rollup cannot recover. One row per (batch, period, client, line, region)
-- with flags for the two real query modes (exclusion list is always {} or the
-- canonical LA003/LA004/SS001 set -> a present_nonexcluded flag is sufficient).
-- ---------------------------------------------------------------------------
create table if not exists public.source_of_sales_customer_presence_rollup (
  batch_id            uuid not null references public.source_of_sales_import_batches(id) on delete cascade,
  period              text not null,
  client_code         text not null,
  official_line       text not null default '',
  region_code         text not null default '',
  present_any         boolean not null default true,   -- customer present in (line,region)
  present_nonexcluded boolean not null default true,   -- had >=1 non-confidential product row
  primary key (batch_id, period, client_code, official_line, region_code)
);

create index if not exists source_of_sales_customer_presence_period_idx
  on public.source_of_sales_customer_presence_rollup (period);

-- ---------------------------------------------------------------------------
-- RLS / grants: server-only, accessed solely via SECURITY DEFINER functions
-- (mirrors source_of_sales_import_rows / _summaries in 20260525221715).
-- ---------------------------------------------------------------------------
alter table public.source_of_sales_fact_rollup enable row level security;
alter table public.source_of_sales_customer_presence_rollup enable row level security;

revoke all on table public.source_of_sales_fact_rollup from anon, authenticated;
revoke all on table public.source_of_sales_customer_presence_rollup from anon, authenticated;

grant select, insert, update, delete on table public.source_of_sales_fact_rollup to service_role;
grant select, insert, update, delete on table public.source_of_sales_customer_presence_rollup to service_role;

grant usage, select on sequence public.source_of_sales_fact_rollup_id_seq to service_role;

drop policy if exists source_of_sales_fact_rollup_service_role_all on public.source_of_sales_fact_rollup;
create policy source_of_sales_fact_rollup_service_role_all
on public.source_of_sales_fact_rollup
