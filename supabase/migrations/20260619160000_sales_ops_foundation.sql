-- ════════════════════════════════════════════════════════════════════════════════════════════════
-- Sales Operations Module — foundation schema (fact + performance rollups + DB-backed profiles).
--
-- This is the NEW, parallel data layer for the Sales Operations module. It does NOT touch any
-- source_of_sales_* table; it reuses those only as READ masters (products/bricks/areas/regions +
-- aliases + customer_map) via the application engine. Fully reversible — dropping every sales_ops_*
-- object cannot affect the existing module or its data.
--
-- PERFORMANCE DESIGN (the #1 goal): the dashboard NEVER scans fact rows live. It reads pre-aggregated
-- rollups (tens–~1k rows) or a single jsonb snapshot. The only heavy scan is a SCOPED single-period
-- recompute at commit time, behind a per-function statement_timeout = '45s' (the inherited
-- authenticator 8s cap would otherwise cancel it). Reads never approach that cap.
--
-- REPLACE-NOT-MERGE: re-uploading a (distributor, period) supersedes the prior batch via a partial
-- unique index, then recomputes that period's rollups from the CURRENT fact rows — correctness is
-- structural (no signed deltas, no double counting), and Σ rollup == Σ fact is asserted as an invariant.
--
-- NOTE: apply to STAGING first and verify (history, tables, RLS, a real upload) before any production
-- apply. Production application is explicitly approval-gated.
-- ════════════════════════════════════════════════════════════════════════════════════════════════

-- ── FACT: one row per (distributor, period) upload ──────────────────────────────────────────────
create table if not exists public.sales_ops_import_batches (
  id                        uuid primary key default gen_random_uuid(),
  distributor_code          text not null,
  distributor_name          text not null default '',
  period                    text not null check (period ~ '^[0-9]{4}-[0-9]{2}$'),
  template_key              text not null default 'sales_ops',
  file_name                 text not null default '',
  sheet_name                text not null default '',
  status                    text not null default 'validated' check (status in ('blocked','validated','superseded')),
  is_current                boolean not null default true,
  supersedes_batch_id       uuid null references public.sales_ops_import_batches(id) on delete set null,
  superseded_by_batch_id    uuid null references public.sales_ops_import_batches(id) on delete set null,
  -- reconciliation counters (the no-silent-loss spine; the app asserts the identity before commit)
  scanned_data_rows         integer not null default 0,
  fully_coded_rows          integer not null default 0,
  exception_rows            integer not null default 0,
  excluded_bonus_rows       integer not null default 0,
  blank_key_rows            integer not null default 0,
  inserted_fact_rows        integer not null default 0,
  total_qty                 numeric(18,6) not null default 0,
  total_value               numeric(18,6) not null default 0,
  recognition_engine_version text null,
  uploaded_by               text not null default 'system',
  committed_at              timestamptz null,
  created_at                timestamptz not null default now(),
  updated_at                timestamptz not null default now()
);

-- Exactly one CURRENT validated batch per (distributor, period) — the structural double-count guard.
create unique index if not exists sales_ops_import_batches_current_unique
  on public.sales_ops_import_batches (distributor_code, period)
  where is_current and status = 'validated';
create index if not exists sales_ops_import_batches_period_status_idx on public.sales_ops_import_batches (period, status);
create index if not exists sales_ops_import_batches_created_idx on public.sales_ops_import_batches (created_at desc);

