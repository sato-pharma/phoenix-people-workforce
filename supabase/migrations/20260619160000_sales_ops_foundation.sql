-- FUNCTIONS — scoped recompute-on-commit (statement_timeout raised so the inherited 8s cap can't kill it)
-- ════════════════════════════════════════════════════════════════════════════════════════════════

-- Recompute ALL rollups + the snapshot for ONE period from the CURRENT validated fact rows, then
-- assert Σ rollup == Σ fact. Idempotent (safe to re-run); used by commit and by admin/backfill.
create or replace function public.sales_ops_rebuild_period(p_period text)
returns void
language plpgsql
security definer
set search_path = public
set statement_timeout = '45s'
as $$
declare
  v_leaf_value numeric(18,6);
  v_fact_value numeric(18,6);
begin
  if p_period is null or p_period !~ '^[0-9]{4}-[0-9]{2}$' then
    raise exception 'sales_ops_rebuild_period: invalid period %', p_period;
  end if;

  delete from public.sales_ops_rollup_leaf where period = p_period;
  delete from public.sales_ops_rollup_period where period = p_period;
  delete from public.sales_ops_rollup_by_distributor where period = p_period;
  delete from public.sales_ops_rollup_by_line where period = p_period;
  delete from public.sales_ops_rollup_by_region where period = p_period;
  delete from public.sales_ops_rollup_by_area where period = p_period;
  delete from public.sales_ops_rollup_by_brick where period = p_period;
  delete from public.sales_ops_rollup_by_product where period = p_period;
  delete from public.sales_ops_rollup_area_product where period = p_period;
  delete from public.sales_ops_dashboard_snapshot where period = p_period;

  -- Leaf: from current validated fact rows.
  insert into public.sales_ops_rollup_leaf
    (period, distributor_code, official_line, region_code, area_code, brick_id, product_code,
     product_name, family, region_name, area_name, brick_name, row_count, total_qty, total_value, updated_at)
  select f.period, f.distributor_code, f.official_line, f.region_code,
         coalesce(f.area_code, ''), coalesce(f.brick_id, ''), f.product_code,
         max(f.product_name), max(f.family), max(f.region_name),
         coalesce(max(f.area_name), ''), coalesce(max(f.brick_name), ''),
         count(*)::int, sum(f.qty), sum(f.value), now()
  from public.sales_ops_fact_rows f
  join public.sales_ops_import_batches b on b.id = f.batch_id
  where f.period = p_period and b.is_current and b.status = 'validated'
  group by f.period, f.distributor_code, f.official_line, f.region_code,
           coalesce(f.area_code, ''), coalesce(f.brick_id, ''), f.product_code;

  -- Sub-grains: derived from the (small) leaf, not re-scanned from fact.
  insert into public.sales_ops_rollup_by_distributor (period, distributor_code, row_count, total_qty, total_value, updated_at)
  select period, distributor_code, sum(row_count)::int, sum(total_qty), sum(total_value), now()
  from public.sales_ops_rollup_leaf where period = p_period group by period, distributor_code;

  insert into public.sales_ops_rollup_by_line (period, official_line, row_count, total_qty, total_value, updated_at)
  select period, official_line, sum(row_count)::int, sum(total_qty), sum(total_value), now()
  from public.sales_ops_rollup_leaf where period = p_period group by period, official_line;

  insert into public.sales_ops_rollup_by_region (period, region_code, region_name, row_count, total_qty, total_value, updated_at)
  select period, region_code, max(region_name), sum(row_count)::int, sum(total_qty), sum(total_value), now()
  from public.sales_ops_rollup_leaf where period = p_period group by period, region_code;

  insert into public.sales_ops_rollup_by_area (period, region_code, area_code, area_name, row_count, total_qty, total_value, updated_at)
  select period, max(region_code), area_code, max(area_name), sum(row_count)::int, sum(total_qty), sum(total_value), now()
  from public.sales_ops_rollup_leaf where period = p_period group by period, area_code;

  insert into public.sales_ops_rollup_by_brick (period, region_code, area_code, brick_id, brick_name, row_count, total_qty, total_value, updated_at)
  select period, max(region_code), max(area_code), brick_id, max(brick_name), sum(row_count)::int, sum(total_qty), sum(total_value), now()
  from public.sales_ops_rollup_leaf where period = p_period and brick_id <> '' group by period, brick_id;

  insert into public.sales_ops_rollup_by_product (period, product_code, product_name, family, official_line, row_count, total_qty, total_value, updated_at)
  select period, product_code, max(product_name), max(family), max(official_line), sum(row_count)::int, sum(total_qty), sum(total_value), now()
  from public.sales_ops_rollup_leaf where period = p_period group by period, product_code;

  insert into public.sales_ops_rollup_area_product (period, area_code, product_code, row_count, total_qty, total_value, updated_at)
  select period, area_code, product_code, sum(row_count)::int, sum(total_qty), sum(total_value), now()
  from public.sales_ops_rollup_leaf where period = p_period group by period, area_code, product_code;

  -- Period totals (only when the period has data).
  insert into public.sales_ops_rollup_period
    (period, total_qty, total_value, row_count, distributor_count, area_count, brick_count, product_count, updated_at)
  select period, sum(total_qty), sum(total_value), sum(row_count)::int,
         count(distinct distributor_code)::int,
         (count(distinct area_code) filter (where area_code <> ''))::int,
         (count(distinct brick_id) filter (where brick_id <> ''))::int,
         count(distinct product_code)::int, now()
  from public.sales_ops_rollup_leaf where period = p_period
  group by period having count(*) > 0;

  -- Snapshot: the whole default dashboard as one jsonb row (built from the small rollups).
  insert into public.sales_ops_dashboard_snapshot (period, line_scope, payload, fact_value_total, built_at)
  select p_period, 'ALL',
    jsonb_build_object(
      'period', p_period,
      'totals', coalesce((select to_jsonb(t) from public.sales_ops_rollup_period t where t.period = p_period), '{}'::jsonb),
      'byDistributor', coalesce((select jsonb_agg(to_jsonb(d) order by d.total_value desc) from public.sales_ops_rollup_by_distributor d where d.period = p_period), '[]'::jsonb),
      'byLine', coalesce((select jsonb_agg(to_jsonb(l) order by l.total_value desc) from public.sales_ops_rollup_by_line l where l.period = p_period), '[]'::jsonb),
      'byRegion', coalesce((select jsonb_agg(to_jsonb(r) order by r.total_value desc) from public.sales_ops_rollup_by_region r where r.period = p_period), '[]'::jsonb),
      'byArea', coalesce((select jsonb_agg(to_jsonb(a) order by a.total_value desc) from public.sales_ops_rollup_by_area a where a.period = p_period), '[]'::jsonb),
      'byProduct', coalesce((select jsonb_agg(to_jsonb(p) order by p.total_value desc) from public.sales_ops_rollup_by_product p where p.period = p_period), '[]'::jsonb)
    ),
    coalesce((select sum(total_value) from public.sales_ops_rollup_leaf where period = p_period), 0),
    now();

  -- Reconciliation invariant: Σ rollup == Σ fact for this period (tolerance for Office 6-dp fractions).
  select coalesce(sum(total_value), 0) into v_leaf_value from public.sales_ops_rollup_leaf where period = p_period;
  select coalesce(sum(f.value), 0) into v_fact_value
  from public.sales_ops_fact_rows f join public.sales_ops_import_batches b on b.id = f.batch_id
  where f.period = p_period and b.is_current and b.status = 'validated';
  if abs(v_leaf_value - v_fact_value) > 0.000001 then
    raise exception 'sales_ops rollup mismatch for period %: leaf=% fact=%', p_period, v_leaf_value, v_fact_value;
  end if;
end;
$$;

-- Commit a staged batch: supersede the prior current batch (atomic via the partial unique index),
-- mark this one current+validated, then recompute that period's rollups. One transaction.
create or replace function public.sales_ops_commit_batch(p_batch_id uuid)
returns void
language plpgsql
security definer
set search_path = public
set statement_timeout = '45s'
as $$
declare
  v_distributor text;
  v_period text;
begin
  select distributor_code, period into v_distributor, v_period
  from public.sales_ops_import_batches where id = p_batch_id;
  if v_period is null then
    raise exception 'sales_ops_commit_batch: batch % not found', p_batch_id;
  end if;

  update public.sales_ops_import_batches
     set is_current = false, status = 'superseded', superseded_by_batch_id = p_batch_id, updated_at = now()
   where distributor_code = v_distributor and period = v_period and is_current = true and status = 'validated' and id <> p_batch_id;

  update public.sales_ops_import_batches
     set is_current = true, status = 'validated', supersedes_batch_id = coalesce(supersedes_batch_id, null), committed_at = now(), updated_at = now()
   where id = p_batch_id;

  perform public.sales_ops_rebuild_period(v_period);
end;
$$;

-- Thin reader: the whole dashboard for a period as one jsonb (zero-join fast path for the UI).
create or replace function public.sales_ops_dashboard(p_period text)
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select coalesce((select payload from public.sales_ops_dashboard_snapshot where period = p_period and line_scope = 'ALL'), '{}'::jsonb);
$$;

