  id                bigint generated by default as identity primary key,
  batch_id          uuid not null references public.sales_ops_import_batches(id) on delete cascade,
  raw_row_number    integer not null,
  distributor_code  text not null,
  period            text not null,            -- = invoiceDate (YYYY-MM), denormalized for index locality
  official_line     text not null default 'Unknown',
  region_code       text not null,            -- 'NATIONAL' allowed (Office fallback)
  region_name       text not null default '',
  area_code         text null,                -- null for the NATIONAL bucket
  area_name         text null,
  brick_id          text null,                -- null for the NATIONAL bucket
  brick_name        text null,
  product_code      text not null,
  product_name      text not null default '',
  family            text not null default '',
  client_code       text null,
  client_name       text null,
  client_address    text null,
  qty               numeric(18,6) not null default 0,  -- fractional for Office allocation
