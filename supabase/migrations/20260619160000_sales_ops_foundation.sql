grant usage, select on sequence public.sales_ops_fact_rows_id_seq to service_role;

-- service_role full-access policy (every table)
do $$
declare t text;
begin
  foreach t in array array[
    'sales_ops_import_batches','sales_ops_fact_rows','sales_ops_rollup_leaf','sales_ops_rollup_period',
    'sales_ops_rollup_by_distributor','sales_ops_rollup_by_line','sales_ops_rollup_by_region',
    'sales_ops_rollup_by_area','sales_ops_rollup_by_brick','sales_ops_rollup_by_product',
    'sales_ops_rollup_area_product','sales_ops_dashboard_snapshot','sales_ops_distributor_profile'
  ] loop
    execute format('drop policy if exists %1$s_service_role_all on public.%1$s', t);
    execute format('create policy %1$s_service_role_all on public.%1$s for all to service_role using (true) with check (true)', t);
  end loop;
end $$;

-- authenticated read policy (rollups + snapshot + profile only; aggregates/config, no PII)
do $$
declare t text;
begin
  foreach t in array array[
    'sales_ops_rollup_leaf','sales_ops_rollup_period','sales_ops_rollup_by_distributor',
    'sales_ops_rollup_by_line','sales_ops_rollup_by_region','sales_ops_rollup_by_area',
    'sales_ops_rollup_by_brick','sales_ops_rollup_by_product','sales_ops_rollup_area_product',
    'sales_ops_dashboard_snapshot','sales_ops_distributor_profile'
  ] loop
    execute format('drop policy if exists %1$s_authenticated_read on public.%1$s', t);
    execute format('create policy %1$s_authenticated_read on public.%1$s for select to authenticated using (true)', t);
  end loop;
end $$;

-- Functions: write/rebuild = service_role only; the dashboard reader = authenticated.
revoke all on function public.sales_ops_rebuild_period(text) from public, anon, authenticated;
revoke all on function public.sales_ops_commit_batch(uuid) from public, anon, authenticated;
grant execute on function public.sales_ops_rebuild_period(text) to service_role;
grant execute on function public.sales_ops_commit_batch(uuid) to service_role;
grant execute on function public.sales_ops_dashboard(text) to authenticated, service_role;
