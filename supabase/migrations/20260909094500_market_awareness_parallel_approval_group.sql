-- Market Awareness — the single manager step becomes a PARALLEL approval group.
--
-- THE OWNER'S RULE, 2026-09-09. A Product Manager or the Group Product Manager submits. It then goes
-- to the Marketing Manager AND the National Sales Manager of the primary line AT THE SAME TIME — and
-- to the NSM of every further line the activity targets. Once all of them have approved, it moves to
-- the CEO, who still decides. Every member of the group may approve, reject, return, or HOLD.
--
-- WHAT THIS REPLACES. `pending_manager` routed to ONE person, resolved from the requester's own
-- reporting line and frozen. That made the Group Product Manager the approver for one Product
-- Manager and the Marketing Manager the approver for the other, and it put no sales manager in the
-- chain at all — an awareness activity is held in a brick that a National Sales Manager owns, and he
-- learned of it only once the CEO had already approved the spend.
--
-- A SLOT IS A ROLE AND A LINE, NEVER A PERSON. The step being replaced was identity-based for a good
-- reason ("his direct manager" names one person). This one names roles, so the slot carries the role
-- and the line and the holder is resolved from the directory. That difference is load-bearing: the
-- Marketing Manager was on leave with the Group Product Manager covering him for a fortnight in
-- August, and a slot frozen to one person deadlocks the queue for the length of a holiday. The
-- holder resolved at submit is still stored — the notification and the screen both need a name — but
-- it is who the slot was SENT to, never who is permitted to answer it.
--
-- "National Sales Manager" is held by THREE people, one per line (Magdy El Senosey on Anti Infective,
-- Ali Elsayed on Pedia, Amr Elsebaey on CNS). A role check with no line in it would put all three on
-- every activity, so the slot carries `line_id` and the application checks the line as well as the
-- role.

-- ─────────────────────────────────────────────────────────────────────────────
-- 1. The approval group
-- ─────────────────────────────────────────────────────────────────────────────

create table if not exists public.market_awareness_activity_approvers (
  id bigint generated by default as identity primary key,
  activity_id uuid not null references public.market_awareness_activities(id) on delete cascade,

  -- Which approval this is. `nsm` carries the line it answers for; `marketing_manager` does not,
  -- because the Marketing Manager is not on a sales line.
  approver_role text not null,
  line_id bigint references public.lines(id),
  is_primary_line boolean not null default false,

  -- Who it was ROUTED to at submit. Display and notification only. A stand-in holding the same role
  -- may answer the slot, and `decided_by_hr_id` is then who actually did.
  assigned_hr_id text,

  decision text,
  decided_by_hr_id text,
  decided_at timestamptz,
  comment text,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint market_awareness_approvers_role_check
    check (approver_role in ('marketing_manager', 'nsm')),
  -- HOLD IS ABSENT FROM THIS LIST ON PURPOSE. A hold is not an answer to "do you approve" — it is a
  -- freeze on the whole request, recorded on the activity and in the decision trail. Writing it into
  -- a slot would make a paused approver indistinguishable from one who had answered.
  constraint market_awareness_approvers_decision_check
    check (decision is null or decision in ('approve', 'reject', 'return')),
  -- An `nsm` slot without a line could be answered by any of the three. A `marketing_manager` slot
  -- with one would claim a line he does not sit on.
  constraint market_awareness_approvers_line_shape
    check (
      (approver_role = 'nsm' and line_id is not null)
      or (approver_role = 'marketing_manager' and line_id is null)
    ),
  -- A decided slot must say who decided it and when. This is a spending approval; a slot that moved
  -- with no attribution is the whole audit trail missing.
  constraint market_awareness_approvers_decided_attributed
    check (
      decision is null
      or (btrim(coalesce(decided_by_hr_id, '')) <> '' and decided_at is not null)
    )
);

-- One slot per role-and-line on an activity. Two `nsm` rows for one line would ask the same person
-- twice and could never both be answered.
create unique index if not exists market_awareness_approvers_one_per_role_line
  on public.market_awareness_activity_approvers (activity_id, approver_role, coalesce(line_id, -1));

create index if not exists market_awareness_approvers_activity_idx
  on public.market_awareness_activity_approvers (activity_id);
-- The inbox and the nav badge both ask "what is still waiting on me", which is this index.
create index if not exists market_awareness_approvers_pending_idx
  on public.market_awareness_activity_approvers (assigned_hr_id)
  where decision is null;

