-- ─────────────────────────────────────────────────────────────────────────────
-- 7. The two in-flight requests
-- ─────────────────────────────────────────────────────────────────────────────
--
-- Both are Nahed Hattab's, both Anti Infective, both already approved by Marketing Manager Hossam
-- Abdelghafar under the old single-manager chain, both sitting with the CEO. The owner's decision of
-- 2026-09-09: move them into the new flow with Hossam's approval COUNTED, waiting on Magdy El
-- Senosey as the Anti Infective National Sales Manager.
--
-- NOTHING IS INVENTED. Hossam's slot is marked approved from his OWN existing decision row — its
-- actor and its timestamp — and no decision row is written for anybody. A system actor writing a
-- decision under a manager's identity is what made three NSMs appear to have approved as the CEO on
-- the weekly plans, and this migration does not repeat it. If his real decision row cannot be found,
-- the activity is left exactly where it is rather than being given an approval nobody made.

do $backfill$
declare
  v_activity record;
  v_mm record;
  v_nsm_hr_id text;
  v_nsm_line_id bigint;
  v_moved integer := 0;
  v_skipped integer := 0;
begin
  for v_activity in
    select a.id, a.primary_line_id, a.activity_code
      from public.market_awareness_activities a
     where a.status = 'pending_ceo'
       and not exists (
         select 1 from public.market_awareness_activity_approvers ap
          where ap.activity_id = a.id
       )
  loop
    -- His real approval, by name, from the append-only trail.
    select d.actor_hr_id, d.created_at
      into v_mm
      from public.market_awareness_decisions d
     where d.activity_id = v_activity.id
       and d.step_code = 'manager'
       and d.action = 'approve'
     order by d.created_at
     limit 1;

    if not found then
      v_skipped := v_skipped + 1;
      continue;
    end if;

    -- The National Sales Manager of the activity's PRIMARY line, resolved live rather than named
    -- here, so a seat change between writing this and applying it cannot strand the request.
    select au.hr_id, e.line_id
      into v_nsm_hr_id, v_nsm_line_id
      from public.app_auth_users au
      join public.employees e on lower(e.hr_id) = lower(au.hr_id)
     where au.is_active
       and lower(btrim(au.role)) = 'national sales manager'
       and e.line_id = v_activity.primary_line_id
     limit 1;

    if v_nsm_hr_id is null then
      v_skipped := v_skipped + 1;
      continue;
    end if;

    insert into public.market_awareness_activity_approvers
      (activity_id, approver_role, line_id, is_primary_line, assigned_hr_id,
       decision, decided_by_hr_id, decided_at, comment)
    values
      (v_activity.id, 'marketing_manager', null, false, v_mm.actor_hr_id,
       'approve', v_mm.actor_hr_id, v_mm.created_at,
       'Approved under the single-manager chain, before the parallel group replaced it.'),
      (v_activity.id, 'nsm', v_nsm_line_id, true, v_nsm_hr_id,
       null, null, null, null);

    update public.market_awareness_activities
       set status = 'pending_group',
           -- His clock starts now. He has only just been asked, so measuring from the original
           -- submission would hand him a request that arrives already breached.
           step_opened_at = now()
     where id = v_activity.id;

    v_moved := v_moved + 1;
  end loop;

  raise notice 'market awareness: % in-flight activities moved into the parallel group, % left alone',
    v_moved, v_skipped;
end;
$backfill$;

-- Everything submitted from here on gets its clock at submit. Anything already past the group keeps
-- a null one, which the badge reads as "no clock" and never as "late".
update public.market_awareness_activities
   set step_opened_at = coalesce(step_opened_at, submitted_at)
 where status in ('pending_group', 'pending_ceo')
   and step_opened_at is null;

-- ─────────────────────────────────────────────────────────────────────────────
-- 8. Prove it, rather than report success and hope
-- ─────────────────────────────────────────────────────────────────────────────

do $verify$
declare
  v_rls boolean;
  v_anon boolean;
  v_group_step integer;
  v_manager_active integer;
  v_bad_status integer;
  v_orphan_group integer;
begin
  -- pg_class, not the ledger: a migration file written is not a migration applied.
  if not exists (
    select 1 from pg_class c
    join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public'
      and c.relname = 'market_awareness_activity_approvers'
      and c.relkind = 'r'
  ) then
    raise exception 'market awareness: the approvers table was not created';
  end if;

  select c.relrowsecurity into v_rls
    from pg_class c
    join pg_namespace n on n.oid = c.relnamespace
   where n.nspname = 'public' and c.relname = 'market_awareness_activity_approvers';
  if not v_rls then
    raise exception 'market awareness: RLS is not enabled on the approvers table';
  end if;

  if not exists (
    select 1 from pg_proc p
    join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public' and p.proname = 'phx_market_awareness_apply_group_decision'
  ) then
    raise exception 'market awareness: phx_market_awareness_apply_group_decision was not created';
  end if;

  -- A SECURITY DEFINER function reachable by anon would hand the browser key the ability to approve
  -- spending. Proven absent rather than assumed.
  select has_function_privilege('anon', p.oid, 'EXECUTE') into v_anon
    from pg_proc p
    join pg_namespace n on n.oid = p.pronamespace
   where n.nspname = 'public' and p.proname = 'phx_market_awareness_apply_group_decision';
  if v_anon then
    raise exception 'market awareness: anon can execute the group decision function';
  end if;

  select count(*) into v_group_step
    from public.market_awareness_workflow_steps where step_code = 'group' and active;
  if v_group_step <> 1 then
    raise exception 'market awareness: expected the group step to be active, found %', v_group_step;
  end if;

  select count(*) into v_manager_active
    from public.market_awareness_workflow_steps where step_code = 'manager' and active;
  if v_manager_active <> 0 then
    raise exception 'market awareness: the retired manager step is still active';
  end if;

  select count(*) into v_bad_status
    from public.market_awareness_activities where status = 'pending_manager';
  if v_bad_status <> 0 then
    raise exception 'market awareness: % activities are still pending_manager', v_bad_status;
  end if;

  -- A request in the group with no group is a request nobody can approve, and it looks exactly like
  -- one somebody is being slow about.
  select count(*) into v_orphan_group
    from public.market_awareness_activities a
   where a.status in ('pending_group', 'on_hold')
     and not exists (
       select 1 from public.market_awareness_activity_approvers ap where ap.activity_id = a.id
     );
  if v_orphan_group <> 0 then
    raise exception 'market awareness: % activities sit in the group with no approvers', v_orphan_group;
  end if;

  raise notice
    'market awareness: approvers table + RLS, group decision function (anon refused), group step active, manager step retired';
end;
