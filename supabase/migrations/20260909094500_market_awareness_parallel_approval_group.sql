  add constraint market_awareness_activities_hold_shape check (
    (status = 'on_hold'
       and btrim(coalesce(held_by_hr_id, '')) <> ''
       and held_at is not null
       and btrim(coalesce(hold_reason, '')) <> '')
    or (status <> 'on_hold' and held_by_hr_id is null and held_at is null and hold_reason is null)
