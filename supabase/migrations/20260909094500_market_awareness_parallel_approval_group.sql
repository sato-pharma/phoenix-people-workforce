-- LEAVING `on_hold` ALWAYS CLEARS THE FREEZE, whichever path leaves it.
--
-- Release goes through the group function, which clears all three. But a held request is still its
-- OWNER's to pull back — `on_hold -> withdrawn` is a legal transition — and that path runs through
-- `phx_market_awareness_apply_decision`, which knows nothing about these columns. Without this the
-- withdraw would fail the constraint above with a check violation the requester reads as "it did not
-- go through", for the one action he is entitled to take on a request nobody else will move.
--
-- A trigger rather than a fix in each caller: there are four write paths into this table today and
-- the next one will not remember either.

create or replace function public.market_awareness_clear_hold_on_exit()
returns trigger
language plpgsql
as $clear_hold$
begin
  if new.status is distinct from 'on_hold' then
    new.held_by_hr_id := null;
    new.held_at := null;
    new.hold_reason := null;
  end if;
  return new;
end;
$clear_hold$;

drop trigger if exists market_awareness_activities_clear_hold on public.market_awareness_activities;
create trigger market_awareness_activities_clear_hold
  before update on public.market_awareness_activities
  for each row execute function public.market_awareness_clear_hold_on_exit();

