-- ─────────────────────────────────────────────────────────────────────────────
-- 5. One group decision and its audit row, in one statement
-- ─────────────────────────────────────────────────────────────────────────────
--
-- Same contract as `phx_market_awareness_apply_decision`, which still serves the CEO step untouched:
-- both writes inside one function body, a row lock, and a refusal to write at all when the activity
-- has moved since the caller read it. New capability ships BESIDE the working one rather than being
-- folded into it — the CEO step's behaviour is unchanged and provably so.
--
-- WHAT IS NEW IS THE GATE. An approval fills one slot and then asks whether the OTHERS have all been
-- filled. That question is asked here, after the write, inside the same lock — asking it in
-- TypeScript before the write is how two approvals arriving together both read "one still pending"
-- and neither moves the request to the CEO.
--
-- THE BUSINESS RULES STAY IN TYPESCRIPT. Who may answer a slot is decided by
-- src/lib/market-awareness/approvers.ts. This function refuses an impossible WRITE and computes the
-- gate; it does not re-implement the routing.

create or replace function public.phx_market_awareness_apply_group_decision(
  p_activity_id uuid,
  p_expected_status text,
  p_action text,
  p_actor_hr_id text,
  p_slot_id bigint default null,
  p_comment text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_status text;
  v_held_at timestamptz;
  v_step_opened_at timestamptz;
  v_slot record;
  v_next_status text;
  v_pending integer;
  v_refused integer;
  v_now timestamptz := now();
begin
  if coalesce(btrim(p_actor_hr_id), '') = '' then
    raise exception 'market awareness: a decision cannot be recorded without an actor'
      using errcode = 'check_violation';
  end if;

  if p_action not in ('approve', 'reject', 'return', 'hold', 'release') then
    raise exception 'market awareness: % is not a group action', p_action
      using errcode = 'check_violation';
  end if;

  -- FOR UPDATE, so a second decision arriving at the same moment waits here and then reads the
  -- status this one wrote, rather than the status both of them read a moment ago.
  select status, held_at, step_opened_at
    into v_status, v_held_at, v_step_opened_at
    from public.market_awareness_activities
   where id = p_activity_id
   for update;

  if not found then
    raise exception 'market awareness: activity % does not exist', p_activity_id
      using errcode = 'no_data_found';
  end if;

  if v_status is distinct from p_expected_status then
    -- Not an error: somebody else decided it first. NOTHING has been written.
    return jsonb_build_object('applied', false, 'currentStatus', v_status);
  end if;

  if p_action in ('approve', 'reject', 'return') then
    if p_slot_id is null then
      raise exception 'market awareness: a group % needs the slot it answers', p_action
        using errcode = 'check_violation';
    end if;

    select * into v_slot
      from public.market_awareness_activity_approvers
     where id = p_slot_id
       and activity_id = p_activity_id
     for update;

    if not found then
      raise exception 'market awareness: approver slot % does not belong to activity %',
        p_slot_id, p_activity_id
        using errcode = 'no_data_found';
    end if;

    if v_slot.decision is not null then
      -- A double-click, or two tabs. Already answered is a real answer, not a failure.
      return jsonb_build_object(
        'applied', false,
        'currentStatus', v_status,
        'reason', 'slot_already_decided'
      );
    end if;

    update public.market_awareness_activity_approvers
       set decision         = p_action,
           decided_by_hr_id = p_actor_hr_id,
           decided_at       = v_now,
           comment          = nullif(btrim(coalesce(p_comment, '')), '')
     where id = p_slot_id;

    if p_action = 'approve' then
      -- The gate, asked of the rows as they now stand — this approval included.
      select count(*) filter (where decision is null),
             count(*) filter (where decision is not null and decision <> 'approve')
        into v_pending, v_refused
        from public.market_awareness_activity_approvers
       where activity_id = p_activity_id;

      -- Positive: everybody answered AND every answer was yes. "Nothing outstanding" would move an
      -- activity with no approvers at all straight to the CEO with nobody having looked at it.
      if v_pending = 0 and v_refused = 0 then
        v_next_status := 'pending_ceo';
      else
        v_next_status := 'pending_group';
      end if;
    elsif p_action = 'reject' then
      v_next_status := 'rejected';
    else
      v_next_status := 'returned';
    end if;

  elsif p_action = 'hold' then
    if coalesce(btrim(p_comment), '') = '' then
      raise exception 'market awareness: a hold has to say why'
        using errcode = 'check_violation';
    end if;
    v_next_status := 'on_hold';
  else
    v_next_status := 'pending_group';
  end if;

  update public.market_awareness_activities
     set status           = v_next_status,
         updated_by_hr_id = p_actor_hr_id,
         rejected_at      = case when v_next_status = 'rejected' then v_now else rejected_at end,
         returned_at      = case when v_next_status = 'returned' then v_now else returned_at end,
         held_by_hr_id    = case when p_action = 'hold' then p_actor_hr_id
                                 when p_action = 'release' then null
                                 else held_by_hr_id end,
         held_at          = case when p_action = 'hold' then v_now
                                 when p_action = 'release' then null
                                 else held_at end,
         hold_reason      = case when p_action = 'hold' then nullif(btrim(coalesce(p_comment, '')), '')
                                 when p_action = 'release' then null
                                 else hold_reason end,
         -- The CEO's clock starts when the group finishes, not when the activity was submitted.
         -- On release the clock is advanced by exactly how long it sat frozen, so a hold stops it
         -- instead of hiding a breach that had already accrued.
         step_opened_at   = case
                              when v_next_status = 'pending_ceo' then v_now
                              when p_action = 'release' and v_held_at is not null
                                then coalesce(v_step_opened_at, v_held_at) + (v_now - v_held_at)
                              else step_opened_at
                            end
   where id = p_activity_id;

  -- ONE decision row, under the identity of whoever actually acted. If this raises, everything above
  -- goes with it — which is the entire point of doing it here.
  insert into public.market_awareness_decisions (
    activity_id, step_code, actor_hr_id, action, comment
  ) values (
    p_activity_id, 'group', p_actor_hr_id, p_action,
    nullif(btrim(coalesce(p_comment, '')), '')
  );

  return jsonb_build_object(
    'applied', true,
    'currentStatus', v_next_status,
    'groupComplete', v_next_status = 'pending_ceo'
  );
end;
$$;

