-- Weekly attendance digest — RELEASED, not silent. Owner decision 2026-09-15, replacing the
-- 2026-09-08 "silent, passive and private" ruling.
--
-- What he asked for, in his words: the review belongs in the admin section, "before pumping
-- notifications to employees i must approve this", and the notice does not ask the employee
-- whether the day is right — "it asks deduct from salary or from balance if available". Then,
-- after the employee decides, "ask him if want a dispute". Answers given in chat the same day:
--   • balance = ANNUAL only, the same number of days as the deduction
--   • channels = in-app + Telegram, never email
--   • an unanswered day goes to SALARY after 2 working days
--
-- THE NEW LIFECYCLE
--   awaiting_release  generated by the daily job; visible ONLY on the admin review page, where a
--                     day can be removed before anyone sees it
--   open              released by the Super Admin; the employee is notified and has until
--                     `answer_due_on` (2 working days) to choose salary or annual balance
--   settled           every day has a final answer
--   void              every day was removed, or a trial-run week that is never released
--
-- WHY A SEPARATE LEDGER FOR BALANCE CHARGES, and not payroll_copilot_vacation_settlements.
-- That ledger belongs to payroll runs: its rows carry a run_id, are superseded (superseded_at)
-- when a run re-decides its vacation step, and a run can deliberately ignore its own rows
-- (balanceSettledDaysInPeriod's excludeSettlementRunId). An attendance answer is not a payroll
-- run and must never be superseded by one. attendance_annual_balance_charges has one writer,
-- three decimals (a digest day can be 0.125), and no supersede path at all.
--
-- WHY phx_apply_vacation_paid_approval IS REDEFINED HERE. It re-derives an employee's used paid
-- days under an advisory lock at the moment a leave request is approved, and it reads ONLY
-- v2_vacation_requests. Without adding the new ledger to that sum, half a day charged to annual
-- balance on Monday would be spent again by a leave request approved on Tuesday. The body below
-- is the definition in 20260711135352_phoenix_production_schema_baseline.sql, which production
-- still serves (compared 2026-09-15), with one addition, marked.

begin;

