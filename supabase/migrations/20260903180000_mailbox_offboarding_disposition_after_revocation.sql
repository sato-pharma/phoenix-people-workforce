-- Mailbox offboarding — let a disposition be recorded on an already-revoked row.
--
-- THE DEFECT. `phx_mailbox_offboarding_record` froze a revoked row against every step except
-- `reopen`. Recording steps 1 and 2 is precisely what makes a row revoked. So the workspace's own
-- third step — "3 · What happened to the mailbox" — became unreachable the moment the first two
-- were recorded, which is the order the screen numbers them in. It did not error: the card simply
-- stops rendering the Record button once the row is settled, so the step disappeared rather than
-- refusing, and nobody ever saw a failure.
--
-- The result, measured on production on 2026-09-03 across all 60 rows:
--
--   disposition        rows   of those, with BOTH revocation steps recorded
--   (none recorded)      57                                             57
--   deleted               2                                              0
--   retained              1                                              1   <- written by hand
--
-- A disposition existed ONLY where it had been recorded INSTEAD of the two steps — `deleted` and
-- `suspended` short-circuit the status to revoked on their own, so they are recordable first. It
-- never once existed AFTER them. Fifty-seven closed mailboxes carry no record of what became of
-- them, and under the old guard none could ever be given one.
--
-- `retained` and `forwarding` are the two dispositions that describe a mailbox whose leaver
-- access still had to be cut step by step, so they are exactly the pair the guard made
-- unrecordable.
--
-- WHY THIS IS SAFE, AND WHY IT IS NARROW. The freeze exists to stop a revoked row being silently
-- weakened — the register's whole purpose is to refuse to call a live mailbox shut. A disposition
-- written on a row whose revocation is earned by BOTH timestamps cannot weaken anything: the
-- second arm of `phx_mailbox_offboarding_refresh_status` stays true whatever the disposition
-- says, so the row is still revoked afterwards. It records a fact without touching an assertion.
--
-- A row revoked BY its disposition is the opposite case. `deleted` with neither step recorded is
-- revoked only because nothing is left to authenticate against; changing it to `retained` would
-- drop it back to `in_progress`. That is a correction, not a new fact, and corrections keep going
-- through `reopen` with a written reason — which is what `reopen` exists for. So the exemption is
-- conditioned on both timestamps being present, never on the step name alone.
--
-- Nothing else in the function changes. This file was generated by copying the function block out
-- of 20260830001000_mailbox_offboarding_register.sql and replacing exactly one statement, so every
-- other branch — the coalesce semantics ("the first admin to do it is who did it"), the reopen
-- clearing, the not_applicable branch — is byte-identical to the definition it supersedes.

create or replace function public.phx_mailbox_offboarding_record(
  p_task_id uuid,
  p_step text,
  p_actor text,
  p_disposition text default null,
  p_forwarding_to text default null,
  p_forwarding_expires_on date default null,
  p_reason text default null,
  p_note text default null
)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  v_row public.mailbox_offboarding_tasks%rowtype;
begin
  select * into v_row from public.mailbox_offboarding_tasks where id = p_task_id;
  if not found then
    raise exception 'Mailbox offboarding task % was not found.', p_task_id;
  end if;

  -- A revoked row is frozen against further steps, but NOT against correction — see the 'reopen'
  -- branch below. A register with no correction path is a defect this repository has already paid
  -- for once: the marketing licence verdict is write-once at approval, and because the write gate
  -- requires a step that stops existing the moment the request is decided, not even a Super Admin
  -- can fix a wrong one. It is then displayed on a register indefinitely. The same shape here —
  -- an admin ticking "app passwords cleared" on the wrong row — would permanently assert that a
  -- live mailbox is shut, which is precisely the false negative this whole table exists to prevent.
  --
  -- The one exemption is a disposition on a row already revoked by BOTH steps. It cannot change
  -- the status, so it cannot weaken the assertion the freeze protects; and without it the third
  -- step of the workspace is unreachable in the order the workspace numbers it. The migration
  -- header carries the measurement that found this.
  if v_row.status = 'revoked'
     and p_step <> 'reopen'
     and not (
       p_step = 'disposition'
       and v_row.password_reset_at is not null
       and v_row.app_passwords_cleared_at is not null
     ) then
    raise exception 'This mailbox is already recorded as revoked. Reopen it before recording anything further.';
  end if;

  if p_actor is null or char_length(trim(p_actor)) = 0 then
    raise exception 'A step must record who performed it.';
  end if;

  if p_step = 'password_reset' then
    -- coalesce, not overwrite: the first admin to do it is who did it.
    update public.mailbox_offboarding_tasks
    set password_reset_at = coalesce(password_reset_at, now()),
        password_reset_by = coalesce(password_reset_by, p_actor),
        note = coalesce(nullif(trim(p_note), ''), note),
        updated_at = now()
    where id = p_task_id;

  elsif p_step = 'app_passwords_cleared' then
    update public.mailbox_offboarding_tasks
    set app_passwords_cleared_at = coalesce(app_passwords_cleared_at, now()),
        app_passwords_cleared_by = coalesce(app_passwords_cleared_by, p_actor),
        note = coalesce(nullif(trim(p_note), ''), note),
        updated_at = now()
    where id = p_task_id;

  elsif p_step = 'disposition' then
    if p_disposition is null or p_disposition not in ('deleted', 'suspended', 'forwarding', 'retained') then
      raise exception 'A disposition must be one of deleted, suspended, forwarding or retained.';
    end if;
    if p_disposition = 'forwarding' and (p_forwarding_to is null or char_length(trim(p_forwarding_to)) = 0) then
      raise exception 'Forwarding needs a destination address.';
    end if;

    update public.mailbox_offboarding_tasks
    set disposition = p_disposition,
        disposition_at = now(),
        disposition_by = p_actor,
        forwarding_to = case when p_disposition = 'forwarding' then trim(p_forwarding_to) else null end,
        forwarding_expires_on = case when p_disposition = 'forwarding' then p_forwarding_expires_on else null end,
        note = coalesce(nullif(trim(p_note), ''), note),
        updated_at = now()
    where id = p_task_id;

  elsif p_step = 'reopen' then
    if p_reason is null or char_length(trim(p_reason)) = 0 then
      raise exception 'Reopening a mailbox record needs a written reason.';
    end if;
    -- Clears the current state back to pending. The history is NOT lost: every step writes an
    -- audit row through writeRequiredAuditLog before it calls this function, so what was claimed,
    -- by whom and when survives the correction. This row is current state, the audit log is record.
    update public.mailbox_offboarding_tasks
    set status = 'pending',
        password_reset_at = null,
        password_reset_by = null,
        app_passwords_cleared_at = null,
        app_passwords_cleared_by = null,
        disposition = null,
        disposition_at = null,
        disposition_by = null,
        forwarding_to = null,
        forwarding_expires_on = null,
        revoked_at = null,
        reason = trim(p_reason),
        note = coalesce(nullif(trim(p_note), ''), note),
        updated_at = now()
    where id = p_task_id;
    return 'pending';

  elsif p_step = 'not_applicable' then
    if p_reason is null or char_length(trim(p_reason)) = 0 then
      raise exception 'Marking a mailbox not applicable needs a written reason.';
    end if;
    update public.mailbox_offboarding_tasks
    set status = 'not_applicable',
        reason = trim(p_reason),
        note = coalesce(nullif(trim(p_note), ''), note),
        updated_at = now()
    where id = p_task_id;
    return 'not_applicable';

  else
    raise exception 'Unknown mailbox offboarding step %.', p_step;
  end if;

  return public.phx_mailbox_offboarding_refresh_status(p_task_id);
end;
$$;

