-- ============================================================================
-- New fact table: marketing_roi_request_geo_facts
--
-- Grain: (request_id, distributor_code, region_code). Needed because the
-- existing dimension facts (marketing_roi_region_facts / _distributor_facts)
-- are grouped by (period, region/distributor) — they lose the request_id
-- dimension, so there's no way to ask "how much of THIS request's actual
-- sales value came from region X" without re-deriving it live.
--
-- phx_marketing_roi_fast's top-level summary needs exactly that: when a
-- region/distributor filter is applied, each request's on-track/behind/
-- no-data classification must be recomputed from a region/distributor-scoped
-- actual value, not the whole-request value stored in
-- marketing_roi_request_facts. This table supplies that missing grain.
--
-- Populated by phx_refresh_marketing_roi_facts (next migration) from data it
-- already computes (all_hits) — no new sales computation, just materialized
-- at a finer grain. Same security pattern as the sibling marketing_roi_*_facts
-- tables: RLS enabled, deny-all policy, service_role-only grants (read only
-- ever happens through SECURITY DEFINER RPCs).
-- ============================================================================

create table if not exists public.marketing_roi_request_geo_facts (
  id                   bigint generated by default as identity primary key,
  refresh_run_id       uuid not null references public.marketing_roi_refresh_runs(id),
  request_id           uuid not null references public.marketing_requests(id) on delete cascade,
  distributor_code     text not null,
  region_code          text,
  actual_sales_value   numeric(20,6) not null default 0,
  actual_sales_units   numeric(20,6) not null default 0,
  sales_rows           integer not null default 0,
  calculation_version  text    not null default '1',
  calculated_at        timestamptz not null default now()
);

create unique index if not exists marketing_roi_request_geo_facts_grain_uniq
  on public.marketing_roi_request_geo_facts (request_id, distributor_code, region_code)
  nulls not distinct;

create index if not exists marketing_roi_request_geo_facts_request_idx
  on public.marketing_roi_request_geo_facts (request_id);

create index if not exists marketing_roi_request_geo_facts_region_idx
  on public.marketing_roi_request_geo_facts (region_code)
  where region_code is not null;

create index if not exists marketing_roi_request_geo_facts_distributor_idx
  on public.marketing_roi_request_geo_facts (distributor_code);

alter table public.marketing_roi_request_geo_facts enable row level security;

drop policy if exists marketing_roi_request_geo_facts_no_direct_access on public.marketing_roi_request_geo_facts;
create policy marketing_roi_request_geo_facts_no_direct_access
  on public.marketing_roi_request_geo_facts for all using (false) with check (false);

revoke all on table public.marketing_roi_request_geo_facts from public, anon, authenticated;
grant all on table public.marketing_roi_request_geo_facts to service_role;

notify pgrst, 'reload schema';
