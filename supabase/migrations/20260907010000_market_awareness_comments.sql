-- Market Awareness — the conversation on an activity.
--
-- The owner asked for it in the original spec: a decider can "open a conversation", and a
-- conversation must go to email. That addressing already exists and is HIS rule, set 2026-09-03:
-- email the SUBMITTER, CC the sender and every other participant, in-app and Telegram to everyone
-- except the author. It lives in one place, `src/lib/conversations/notify.ts`, precisely so it does
-- not become four different rules in four modules — so this table stores the messages and nothing
-- here re-implements who gets told.
--
-- APPEND-ONLY BY INTENT. A comment on a spending decision is part of why that decision was made;
-- there is no edit and no delete path, and `market_awareness_decisions` beside it takes the same
-- shape for the same reason. The one deletion that reaches these rows is the activity's own
-- ON DELETE CASCADE, which only fires for a draft nobody has acted on.

create table if not exists public.market_awareness_comments (
  id bigint generated by default as identity primary key,
  activity_id uuid not null references public.market_awareness_activities(id) on delete cascade,
  author_hr_id text not null,
  body text not null,
  created_at timestamptz not null default now(),
  constraint market_awareness_comments_author_not_blank check (btrim(author_hr_id) <> ''),
  -- A blank comment notifies several people about nothing. The UI refuses it too; this is the
  -- backstop, because the UI is not the boundary.
  constraint market_awareness_comments_body_not_blank check (btrim(body) <> '')
);

create index if not exists market_awareness_comments_activity_idx
  on public.market_awareness_comments (activity_id, created_at);

comment on table public.market_awareness_comments is
  'The conversation on an awareness activity. Append-only: a comment on a spending decision is part '
  'of the record of why it was made. Who gets emailed is decided by src/lib/conversations/notify.ts '
  '(owner rule, 2026-09-03) — nothing here restates that.';

-- Same RLS shape as the other nine tables: the app reads and writes through the service-role client
-- and enforces with assertPermission, and RLS is the backstop that keeps a browser-side anon or
-- authenticated key out. REVOKE FROM PUBLIC also strips what service_role held implicitly through
-- the default ACL, so the GRANT below is not optional.
alter table public.market_awareness_comments enable row level security;

drop policy if exists market_awareness_comments_service_role_all on public.market_awareness_comments;
create policy market_awareness_comments_service_role_all
  on public.market_awareness_comments
  for all to service_role using (true) with check (true);

revoke all on table public.market_awareness_comments from anon;
revoke all on table public.market_awareness_comments from authenticated;
revoke all on table public.market_awareness_comments from public;
grant all on table public.market_awareness_comments to service_role;

do $verify$
declare
  has_rls boolean;
begin
  -- pg_class, not the ledger: a migration file written is not a migration applied.
  if not exists (
    select 1 from pg_class c
    join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public' and c.relname = 'market_awareness_comments' and c.relkind = 'r'
  ) then
    raise exception 'market awareness: market_awareness_comments was not created';
  end if;

  select c.relrowsecurity into has_rls
    from pg_class c
    join pg_namespace n on n.oid = c.relnamespace
   where n.nspname = 'public' and c.relname = 'market_awareness_comments';

  if not has_rls then
    raise exception 'market awareness: RLS is not enabled on market_awareness_comments';
  end if;

  raise notice 'market awareness: comments table created, RLS on';
end;
$verify$;
