create index if not exists job_offer_decision_events_offer_created_idx on public.job_offer_decision_events (offer_id, created_at desc);
create index if not exists job_offer_decision_events_ip_created_idx on public.job_offer_decision_events (ip_hash, created_at desc);

alter table public.job_offer_decision_events enable row level security;
alter table public.job_offer_decision_events force row level security;

