  candidate_name text not null,
  candidate_email text not null,
  candidate_phone text null,
  job_title text not null,
  template_key text null,
  area_scope text null,
  area_id bigint null references public.areas(id) on update cascade on delete set null,
  department_id bigint null references public.departments(id) on update cascade on delete set null,
  line_id bigint null references public.lines(id) on update cascade on delete set null,
  manager_hr_id text null references public.employees(hr_id) on update cascade on delete set null,
  position_id bigint null references public.positions(id) on update cascade on delete set null,
  vacancy_id bigint null references public.position_vacancies(id) on update cascade on delete set null,
  salary_amount numeric null,
  base_salary numeric null,
  basic_salary numeric null,
  gross_salary numeric null,
  net_salary numeric null,
  fuel_allowance numeric null,
  extra_cost_of_living numeric null,
  social_insurance numeric null,
  taxes numeric null,
  compensation_lines jsonb not null default '[]'::jsonb,
  compensation_notes text null,
  start_date date null,
  expires_at timestamptz not null,
  status text not null default 'sent' check (status in ('draft', 'sent', 'accepted', 'rejected', 'expired', 'hired', 'withdrawn', 'cancelled', 'voided')),
  secure_token_hash text not null unique,
  token_last_four text not null,
  accepted_at timestamptz null,
  rejected_at timestamptz null,
  expired_at timestamptz null,
  voided_at timestamptz null,
  void_reason text null,
  voided_reserved_employee_hr_id text null,
  employee_hr_id text null references public.employees(hr_id) on update cascade on delete set null,
  reserved_employee_hr_id text null,
  accepted_terms_snapshot jsonb null,
  revoked_at timestamptz null,
  withdrawn_at timestamptz null,
  cancelled_at timestamptz null,
  resend_count integer not null default 0,
  last_sent_at timestamptz null,
  decision_ip_hash text null,
  decision_user_agent text null,
  decision_nonce_hash text null,
  delivery_status text null,
  access_provisioning_status text null,
  access_provisioning_error text null,
  approval_repair_status text null,
  approval_repair_error text null,
  hr_notes text null,
  rejection_reason text null,
  candidate_comments text null,
  approval_checklist jsonb not null default '{}'::jsonb,
  onboarding_status text not null default 'not_started',
  created_by_hr_id text null references public.employees(hr_id) on update cascade on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.job_offer_audit_logs (
  id bigint generated by default as identity primary key,
  offer_id uuid not null references public.job_offers(id) on delete cascade,
  action text not null,
  actor_type text not null default 'system',
  actor_reference text null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.job_offer_decision_events (
  id bigint generated by default as identity primary key,
  offer_id uuid null references public.job_offers(id) on delete cascade,
  action text not null,
  result text not null,
  ip_hash text null,
  user_agent text null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

