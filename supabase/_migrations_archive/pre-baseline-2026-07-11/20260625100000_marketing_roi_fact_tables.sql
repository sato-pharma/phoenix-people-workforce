-- ============================================================================
-- PR 2 — Marketing ROI pre-computed fact tables (schema only)
--
-- These tables hold the output of phx_refresh_marketing_roi_facts() (added in
-- PR 3). Dashboard RPCs (PR 4) read from them instead of re-running the 40+
-- CTE monster on every page load, bringing p95 from ~47s to < 1s.
--
-- Safety rules:
--   • Additive only — no existing tables or functions are modified.
--   • No backfill yet — tables start empty; PR 3 adds the refresh function.
--   • phx_marketing_roi_customer_dashboard() is untouched as fallback.
--   • All tables use CREATE TABLE IF NOT EXISTS so this migration is idempotent.
-- ============================================================================

-- ---------------------------------------------------------------------------
-- Audit / control table — one row per refresh run.
-- Created FIRST because every fact table references it via refresh_run_id.
-- ---------------------------------------------------------------------------
create table if not exists public.marketing_roi_refresh_runs (
  id                  uuid primary key default gen_random_uuid(),
  triggered_by        text not null,         -- 'sos_import' | 'admin_manual'
  trigger_batch_id    uuid,                  -- null for full refresh
  started_at          timestamptz not null default now(),
  finished_at         timestamptz,
  status              text not null default 'running',
  -- running | success | failed | skipped (advisory lock was held)
  error               text,
  affected_periods    text[]  not null default '{}',
  row_counts          jsonb,                 -- {table_name: row_count} per fact table
  calculation_version text                   -- bumped when refresh business logic changes
);

create index if not exists marketing_roi_refresh_runs_status_idx
  on public.marketing_roi_refresh_runs (status, started_at desc);

create index if not exists marketing_roi_refresh_runs_batch_idx
  on public.marketing_roi_refresh_runs (trigger_batch_id)
  where trigger_batch_id is not null;

-- ---------------------------------------------------------------------------
-- Per-request ROI facts — one live row per marketing_request.
--
-- Grain: request_id (unique). Replaced on every refresh that touches the
-- request's ROI window. refresh_run_id tracks which run produced this row
-- so any displayed number can be traced back to a specific refresh and its
-- source batches/periods.
-- ---------------------------------------------------------------------------
create table if not exists public.marketing_roi_request_facts (
  id                     bigint generated by default as identity primary key,
  refresh_run_id         uuid not null references public.marketing_roi_refresh_runs(id),
  request_id             uuid not null references public.marketing_requests(id) on delete cascade,
  request_code           text not null,
  pay_month              text,                   -- YYYY-MM derived from marketing_requests.pay_date
  line_label             text,
  customer_id            uuid,
  customer_name          text,
  customer_code          text,
  estimated_cost         numeric(20,6) not null default 0,
  required_roi_value     numeric(20,6) not null default 0,
  expected_roi_value     numeric(20,6) not null default 0,
  actual_sales_value     numeric(20,6) not null default 0,
  -- From SoS value (direct channel) or qty × factory_price (indirect);
  -- matches the exact business logic in phx_marketing_roi_customer_dashboard.
  actual_sales_units     numeric(20,6) not null default 0,
  factory_price_snapshot numeric(20,6),
  -- Price used at calculation time — kept for auditability so historical ROI
  -- numbers don't silently change when a product price is updated.
  sales_rows             integer not null default 0,
  exact_sales_rows       integer not null default 0,
  fallback_sales_rows    integer not null default 0,
  attribution_quality    text,
  -- exact_customer | brick_fallback | mixed | no_sales
  actual_roi_status      text,
  -- on_track | behind | no_data
  actual_coverage_ratio  numeric(20,6) not null default 0,
  coverage_gap           numeric(20,6) not null default 0,
  expected_gap           numeric(20,6) not null default 0,
  recommended_action     text,
  -- monitor | mapping_review | high_risk_gap | follow_up
  source_batch_ids       uuid[]  not null default '{}',
  source_periods         text[]  not null default '{}',
  calculation_version    text    not null default '1',
  calculated_at          timestamptz not null default now()
);

-- One live row per request — the refresh DELETEs the old row and INSERTs a new one.
create unique index if not exists marketing_roi_request_facts_request_uniq
  on public.marketing_roi_request_facts (request_id);

-- Fast filter patterns for the dashboard summary RPC.
create index if not exists marketing_roi_request_facts_status_idx
  on public.marketing_roi_request_facts (actual_roi_status);

create index if not exists marketing_roi_request_facts_pay_month_idx
  on public.marketing_roi_request_facts (pay_month);

create index if not exists marketing_roi_request_facts_line_idx
  on public.marketing_roi_request_facts (line_label);

create index if not exists marketing_roi_request_facts_customer_idx
  on public.marketing_roi_request_facts (customer_id);

