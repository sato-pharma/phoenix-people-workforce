create table if not exists public.geo_locations (
  id bigint generated by default as identity primary key,
  source_type text not null,
  source_key text not null,
  label text not null,
  address_text text,
  city text,
  area text,
  line text,
  latitude double precision,
  longitude double precision,
  geocode_status text,
  geocode_provider text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.geo_locations
  add column if not exists source_type text,
  add column if not exists source_key text,
  add column if not exists label text,
  add column if not exists address_text text,
  add column if not exists city text,
  add column if not exists area text,
  add column if not exists line text,
  add column if not exists latitude double precision,
  add column if not exists longitude double precision,
  add column if not exists geocode_status text,
  add column if not exists geocode_provider text,
  add column if not exists created_at timestamptz,
  add column if not exists updated_at timestamptz;

update public.geo_locations
set
  source_type = coalesce(source_type, 'custom'),
  source_key = coalesce(source_key, md5(coalesce(address_text, label, 'geo-location'))),
  label = coalesce(label, coalesce(address_text, 'Geo location')),
  created_at = coalesce(created_at, now()),
  updated_at = coalesce(updated_at, now());

alter table public.geo_locations
  alter column source_type set not null,
  alter column source_key set not null,
  alter column label set not null,
  alter column created_at set default now(),
  alter column created_at set not null,
  alter column updated_at set default now(),
  alter column updated_at set not null;

