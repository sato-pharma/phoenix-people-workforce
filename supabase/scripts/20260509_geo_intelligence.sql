create table if not exists public.geo_bricks (
  id bigint generated by default as identity primary key,
  line text,
  area text,
  brick_name text not null,
  brick_code text not null,
  employee_hr_id text,
  employee_name text,
  latitude double precision,
  longitude double precision,
  coverage_status text not null default 'unassigned',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.geo_bricks
  add column if not exists line text,
  add column if not exists area text,
  add column if not exists brick_name text,
  add column if not exists brick_code text,
  add column if not exists employee_hr_id text,
  add column if not exists employee_name text,
  add column if not exists latitude double precision,
  add column if not exists longitude double precision,
  add column if not exists coverage_status text,
  add column if not exists created_at timestamptz,
  add column if not exists updated_at timestamptz;

update public.geo_bricks
set
  brick_name = coalesce(brick_name, 'Unnamed brick'),
  brick_code = coalesce(brick_code, md5(coalesce(brick_name, area, line, 'brick'))),
  coverage_status = coalesce(coverage_status, 'unassigned'),
  created_at = coalesce(created_at, now()),
  updated_at = coalesce(updated_at, now());

alter table public.geo_bricks
  alter column brick_name set not null,
  alter column brick_code set not null,
  alter column coverage_status set default 'unassigned',
  alter column coverage_status set not null,
  alter column created_at set default now(),
  alter column created_at set not null,
  alter column updated_at set default now(),
  alter column updated_at set not null;

create unique index if not exists geo_locations_source_key_idx
  on public.geo_locations (source_type, source_key);

create index if not exists geo_locations_address_idx
  on public.geo_locations (address_text);

create unique index if not exists geo_bricks_code_idx
  on public.geo_bricks (brick_code);

create index if not exists geo_bricks_line_area_idx
  on public.geo_bricks (line, area);

create index if not exists geo_trip_routes_month_status_idx
  on public.geo_trip_routes (source_file_month, status);

create index if not exists geo_trip_routes_employee_idx
  on public.geo_trip_routes (employee_hr_id);
