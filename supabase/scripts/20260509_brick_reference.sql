create table if not exists public.brick_reference_imports (
  id bigint generated by default as identity primary key,
  file_name text not null,
  line text not null,
  row_count integer not null default 0,
  brick_count integer not null default 0,
  uploaded_by text,
  created_at timestamptz not null default now()
);

alter table public.brick_reference_imports
  add column if not exists file_name text,
  add column if not exists line text,
  add column if not exists row_count integer,
  add column if not exists brick_count integer,
  add column if not exists uploaded_by text,
  add column if not exists created_at timestamptz;

update public.brick_reference_imports
set
  file_name = coalesce(file_name, 'brick-reference.xlsx'),
  line = coalesce(line, 'Pedia'),
  row_count = coalesce(row_count, 0),
  brick_count = coalesce(brick_count, 0),
  created_at = coalesce(created_at, now());

alter table public.brick_reference_imports
  alter column file_name set not null,
  alter column line set not null,
  alter column row_count set default 0,
  alter column row_count set not null,
  alter column brick_count set default 0,
  alter column brick_count set not null,
  alter column created_at set default now(),
  alter column created_at set not null;

create table if not exists public.brick_reference_rows (
  id bigint generated by default as identity primary key,
  import_id bigint not null references public.brick_reference_imports(id) on delete cascade,
  line text not null,
  area text not null default '',
  dsm_hr_id text,
  brick_name_raw text not null,
  brick_name_normalized text not null,
  source_details text not null default '',
  source_file_name text,
  source_row integer not null default 0,
  created_at timestamptz not null default now()
);

alter table public.brick_reference_rows
  add column if not exists import_id bigint,
  add column if not exists line text,
  add column if not exists area text,
  add column if not exists dsm_hr_id text,
  add column if not exists brick_name_raw text,
  add column if not exists brick_name_normalized text,
  add column if not exists source_details text,
  add column if not exists source_file_name text,
  add column if not exists source_row integer,
  add column if not exists created_at timestamptz;

update public.brick_reference_rows
set
  area = coalesce(area, ''),
  line = coalesce(line, 'Pedia'),
  brick_name_raw = coalesce(brick_name_raw, ''),
  brick_name_normalized = coalesce(brick_name_normalized, ''),
  source_details = coalesce(source_details, ''),
  source_row = coalesce(source_row, 0),
  created_at = coalesce(created_at, now());

alter table public.brick_reference_rows
  alter column line set not null,
  alter column area set default '',
  alter column area set not null,
  alter column brick_name_raw set not null,
  alter column brick_name_normalized set not null,
  alter column source_details set default '',
  alter column source_details set not null,
  alter column source_row set default 0,
  alter column source_row set not null,
  alter column created_at set default now(),
  alter column created_at set not null;

do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'brick_reference_rows_import_id_fkey'
  ) then
    alter table public.brick_reference_rows
      add constraint brick_reference_rows_import_id_fkey
      foreign key (import_id)
      references public.brick_reference_imports(id)
      on delete cascade;
  end if;
end $$;

create index if not exists brick_reference_imports_line_created_idx
  on public.brick_reference_imports (line, created_at desc);

create index if not exists brick_reference_rows_import_idx
  on public.brick_reference_rows (import_id);

create index if not exists brick_reference_rows_line_brick_idx
  on public.brick_reference_rows (line, brick_name_normalized);

create index if not exists brick_reference_rows_line_area_idx
  on public.brick_reference_rows (line, area);

create index if not exists brick_reference_rows_dsm_hr_id_idx
  on public.brick_reference_rows (dsm_hr_id);
