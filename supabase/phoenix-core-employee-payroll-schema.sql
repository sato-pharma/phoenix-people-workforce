-- Phoenix Workforce core employee + payroll schema.
-- Idempotent: safe to run more than once in Supabase SQL editor.

create extension if not exists pgcrypto;

create table if not exists public.departments (
  id bigint generated by default as identity primary key,
  name text not null unique,
  code text null unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.lines (
  id bigint generated by default as identity primary key,
  name text not null unique,
  code text null unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.areas (
  id bigint generated by default as identity primary key,
  name text not null unique,
  code text null unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.teams (
  id bigint generated by default as identity primary key,
  name text not null unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.positions (
  id bigint generated by default as identity primary key,
  title text not null unique,
  code text null unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.employees (
  hr_id text primary key,
  full_name text not null default '',
  name_ar text null,
  crm_id text null,
  crm_username text null,
  work_email text null,
  mobile_number text null,
  job_title text null,
  hire_date date null,
  employment_status text not null default 'active',
  education text null,
  manager_hr_id text null references public.employees(hr_id) on update cascade on delete set null,
  department_id bigint null references public.departments(id) on update cascade on delete set null,
  line_id bigint null references public.lines(id) on update cascade on delete set null,
  area_id bigint null references public.areas(id) on update cascade on delete set null,
  team_id bigint null references public.teams(id) on update cascade on delete set null,
  position_id bigint null references public.positions(id) on update cascade on delete set null,
  region_name text null,
  birth_date date null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Note: Redundant alter table statements for employees have been removed.
-- Schema remains idempotent through CREATE TABLE IF NOT EXISTS and CREATE INDEX IF NOT EXISTS.

create unique index if not exists employees_crm_id_unique_idx
  on public.employees (crm_id)
  where crm_id is not null and trim(crm_id) <> '';

create unique index if not exists employees_crm_username_unique_idx
  on public.employees (lower(crm_username))
  where crm_username is not null and trim(crm_username) <> '';

create index if not exists employees_manager_hr_id_idx on public.employees (manager_hr_id);
create index if not exists employees_line_id_idx on public.employees (line_id);
create index if not exists employees_area_id_idx on public.employees (area_id);
create index if not exists employees_status_idx on public.employees (employment_status);
create index if not exists employees_job_title_idx on public.employees (job_title);

create table if not exists public.employee_compensation (
  id bigint generated by default as identity primary key,
  employee_hr_id text not null unique references public.employees(hr_id) on update cascade on delete cascade,
  net_salary numeric(20, 2) not null default 0,
  social_insurance numeric(20, 2) not null default 0,
  taxes numeric(20, 2) not null default 0,
  medical_insurance numeric(20, 2) not null default 0,
  comprehensive_wage numeric(20, 2) not null default 0,
  subscription_wage numeric(20, 2) not null default 0,
  fuel_allowance numeric(20, 2) not null default 0,
  extra_cost_of_living numeric(20, 2) not null default 0,
  gross_salary numeric(20, 2) not null default 0,
  salary_details jsonb not null default '[]'::jsonb,
  payment_mode text not null default 'two_parts',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint employee_compensation_payment_mode_check
    check (payment_mode in ('one_part', 'two_parts'))
);

create index if not exists employee_compensation_employee_hr_id_idx
  on public.employee_compensation (employee_hr_id);

create index if not exists employee_compensation_hr_mode_idx
  on public.employee_compensation (employee_hr_id, payment_mode);

