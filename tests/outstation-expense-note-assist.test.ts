import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { join } from "node:path";

import {
  buildExpenseNotePrompt,
  EXPENSE_NOTE_MAX_CHARS,
  findExpenseNoteViolations,
  MAX_NOTE_FACTS,
  normalizeExpenseNoteFacts,
  numericTokens,
  sanitizeSystemNote,
} from "../src/lib/outstation/expense-note-assist.ts";

// Owner request (2026-08-08): in expense approval, "i type roughly my response to every submission
// he rephrase to corporate business language and put it as a note as if the system auto replied
// never the employee now that the hr is the backend".
//
// Two things can go wrong with that, and only two matter enough to fail the call:
//
//   1. VOICE. The whole reason the feature exists is that a decision must stop reading as one named
//      person's verdict. A note that comes back saying "HR has reviewed your claim" or "we adjusted
//      the amount" has done the opposite of what was asked. The owner's separate standing rule
//      (2026-08-04) adds that no user-facing text may reveal a model was involved.
//   2. FIGURES. This note tells an employee what he is being paid and why. A number that was never
//      put in front of the writer is an invented one, and it would be read as authoritative.
//
// Both are asserted here without a network, the same discipline expense-gate.ts uses for the
// payroll gate: the rules that decide what an employee is told about his money must be testable
// without a database or an API key.

const MODULE = join(process.cwd(), "src/lib/outstation/expense-note-assist.ts");
const ROUTE = join(process.cwd(), "app/api/admin/outstation/expenses/note-assist/route.ts");
const WORKSPACE = join(process.cwd(), "src/components/outstation/expense-approvals-workspace.tsx");
// The rewrite control sits in the decision bar since the 2026-11-07 rebuild.
const DECISION_BAR = join(process.cwd(), "src/components/outstation/expense-approvals/decision-bar.tsx");

/** The prompt the model saw for a typical reduced-amount decision. */
const PROMPT = buildExpenseNotePrompt({
  draft: "المبلغ اتحسب مرتين، خصمنا 200",
  facts: [
    { label: "Claimed total", value: "EGP 1,250.00" },
    { label: "Approved amount", value: "EGP 1,050.00" },
    { label: "Deduction", value: "EGP 200.00" },
  ],
  outcome: "adjusted",
});

function violations(note: string, source = PROMPT) {
  return findExpenseNoteViolations(note, source);
}

export function runOutstationExpenseNoteAssistTests() {
  // ── Voice: the reason the feature exists ────────────────────────────────────

  assert.deepEqual(
    violations(
      "The claimed amount exceeds the approved rate for this trip, and the payable amount has been reduced by EGP 200.00 accordingly.",
    ),
    [],
    "a third-person note citing only provided figures must pass",
  );

  assert.ok(
    violations("HR has reviewed this claim and reduced the payable amount.").includes(
      "HR named as the decider",
    ),
    "naming HR as the decider must be refused — that is exactly what the owner asked to remove",
  );

  assert.ok(
    violations("We have adjusted the payable amount for this trip.").includes("first-person voice"),
    "first-person plural must be refused",
  );
  assert.ok(
    violations("I reduced the allowance to one day.").includes("first-person voice"),
    "first-person singular must be refused",
  );
  assert.ok(
    violations("Human Resources confirmed the deduction.").includes("HR named as the decider"),
    "the spelled-out department must be refused as well as the abbreviation",
  );
  assert.ok(
    violations("This summary was generated by AI from the approver's note.").includes("AI attribution"),
    "no user-facing text may reveal a model was involved (owner rule 2026-08-04)",
  );

  // A word that merely CONTAINS a banned token must not trip the check — "hour" holds "our",
  // "their" holds "hei", and a false positive here means a correct note is thrown away.
  assert.deepEqual(
    violations("The trip was recorded as a single working day rather than an overnight stay."),
    [],
    "banned words must match on word boundaries, not as substrings",
  );

  // ── Figures: the note tells an employee what he is owed ─────────────────────

  const invented = violations("The payable amount has been reduced by EGP 500.00 for this trip.");
  assert.equal(invented.length, 1, "an invented figure must be the only complaint about that note");
  assert.ok(
    invented[0].includes("500"),
    "the refusal must name the invented figure so the approver can see what went wrong",
  );

  assert.deepEqual(
    violations("The approved amount for this trip is EGP 1050."),
    [],
    "the same value written a different way (1,050.00 vs 1050) must be recognised as provided",
  );

  // The approver typed "200" himself; it is his figure to publish whatever the fact list carried.
  assert.deepEqual(
    findExpenseNoteViolations(
      "The payable amount has been reduced by 200 for this trip.",
      "Approver's rough note: خصمنا 200",
    ),
    [],
    "a figure the approver wrote himself must be allowed through",
  );

  assert.deepEqual(numericTokens("EGP 1,250.00 over 128 km"), ["1250", "128"]);
  assert.deepEqual(violations(""), ["the rewritten note came back empty"]);

  // ── Structural cleanup ──────────────────────────────────────────────────────

  assert.equal(
    sanitizeSystemNote('```json\n"Dear Ahmed, **The request has been rejected.**\n\nBest regards, HR"\n```'),
    "The request has been rejected.",
    "fences, markdown, a wrapping quote, a greeting and a sign-off must all be stripped to one plain line",
  );

  assert.equal(
    sanitizeSystemNote("- The claim was reduced.\n- The trip was one day."),
    "The claim was reduced. The trip was one day.",
    "a bulleted reply must collapse to a single paragraph — the field it lands in is one line",
  );

  const long = `${"The payable amount has been reduced because the claimed allowance covered a day already paid. ".repeat(4)}Trailing clause`;
  const cut = sanitizeSystemNote(long);
  assert.ok(cut.length <= EXPENSE_NOTE_MAX_CHARS, "an over-long note must be brought under the cap");
  assert.ok(cut.endsWith("."), "the cut must land on a finished sentence");
  assert.ok(
    !cut.includes("…") && !cut.includes("..."),
    "never elide with an ellipsis — the owner's standing rule for every surface in this system",
  );

  // ── Input shaping ───────────────────────────────────────────────────────────

  const facts = normalizeExpenseNoteFacts([
    { label: "Claimed total", value: "EGP 1,250.00" },
    { label: "", value: "dropped: no label" },
    { label: "Approved amount", value: "" },
    ...Array.from({ length: MAX_NOTE_FACTS + 5 }, (_, index) => ({
      label: `Filler ${index}`,
      value: `${index}`,
    })),
  ]);
  assert.equal(facts.length, MAX_NOTE_FACTS, "the browser-supplied fact list must be capped");
  assert.ok(
    facts.every((fact) => fact.label && fact.value),
    "half-empty facts must be dropped rather than reaching the prompt as blanks",
  );

  assert.ok(PROMPT.includes("EGP 1,250.00"), "the prompt must carry the figures the note may cite");
  assert.ok(PROMPT.includes("خصمنا 200"), "the prompt must carry the approver's own words verbatim");
  assert.ok(
    PROMPT.includes("reduced"),
    "the prompt must state which decision is being recorded, so the note leads with the right outcome",
  );

  // ── Wiring: the guards are actually applied, and the route is actually gated ──

  const moduleSource = readFileSync(MODULE, "utf8");
  const polish = moduleSource.slice(moduleSource.indexOf("export async function polishExpenseApprovalNote"));
  assert.ok(
    /findExpenseNoteViolations\(\s*note,/.test(polish),
    "polishExpenseApprovalNote must run the violation check on what came back, not just build a prompt",
  );
  assert.ok(
    /violations\.length > 0/.test(polish) && /throw new ExpenseNoteAssistError/.test(polish),
    "a violating note must fail the call — never be patched over and handed to the approver",
  );
  assert.ok(
    /sanitizeSystemNote\(parseNote\(/.test(polish),
    "the reply must be sanitized before it is checked, or markdown alone would fail every note",
  );

  const routeSource = readFileSync(ROUTE, "utf8");
  assert.ok(
    /assertSameOriginMutation\(request\)/.test(routeSource),
    "the note route is a POST under /api/admin/outstation/**, which the access registry marks CSRF-required",
  );
  assert.ok(
    /assertSystemAdministratorWorkspaceAccess\(/.test(routeSource),
    "note writing is gated on decision access — a read-only CEO has no decision to attach a note to",
  );

  const workspaceSource = readFileSync(WORKSPACE, "utf8") + readFileSync(DECISION_BAR, "utf8");
  assert.ok(
    /Restore my wording/.test(workspaceSource),
    "the approver's own wording must stay one click away from any rewrite",
  );
  assert.ok(
    !/\bAI\b|GPT|OpenAI/.test(workspaceSource),
    "no approvals surface may name a model (owner rule 2026-08-04)",
  );
}
