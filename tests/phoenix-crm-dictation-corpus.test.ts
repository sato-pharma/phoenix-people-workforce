import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { correctDictatedProducts, normalizeArabic } from "../src/lib/phoenix-crm/dictation-correct.ts";
import { COMPETITOR_TERMS, PRODUCT_VOCABULARY } from "../src/lib/phoenix-crm/dictation-vocabulary.ts";

/**
 * The dictation corrector, measured against the words the field force actually writes.
 *
 * WHY A FIXTURE AND NOT THE DATABASE. `scripts/dictation-corrector-eval.ts` runs this same check
 * against all 137,000 live comments, and that is the authoritative run — but it needs production
 * credentials and a quarter of an hour, so it is something a person remembers to do, which means
 * eventually nobody does. The frozen fixture is the same measurement with the corpus standing still:
 * it needs no database, runs in under a second, and runs on every PR.
 *
 * WHAT IS IN THE FIXTURE. Single WORDS and how often each occurs. No sentences, no comment text, no
 * row ids, nothing joining a word back to the rep who wrote it or the doctor it was written about —
 * the check needs the corpus's vocabulary, not its content, and the content is a clinical record
 * that does not belong in a repository. It is narrowed again to words within a few edits of a
 * product name, because that is the only neighbourhood a vocabulary change can reach.
 *
 * WHAT THIS PINS, AND WHY EXACTLY. The counts below are exact, not bounds. The fixture never moves,
 * so the numbers are deterministic, and any edit to the vocabulary or the thresholds moves them.
 * That is the point: the test goes red with the old number and the new one side by side, and
 * re-pinning is a deliberate act taken with the evaluation report in hand rather than a silent
 * widening nobody measured. Changing a pin to make the suite green, without looking at what moved,
 * is the one way to use this file wrongly.
 *
 * Regenerate the fixture with:
 *   node --env-file-if-exists=.env.local --experimental-strip-types \
 *        --experimental-specifier-resolution=node --experimental-loader ./tests/alias-loader.mjs \
 *        scripts/dictation-corrector-eval.ts --freeze tests/fixtures/dictation-corpus-tokens.json
 */

type Fixture = {
  note: string;
  generated: string;
  comments: number;
  distinctTokensInCorpus: number;
  withinEdits: number;
  tokens: Record<string, number>;
};

const FIXTURE_PATH = fileURLToPath(new URL("./fixtures/dictation-corpus-tokens.json", import.meta.url));

/** Exactly what the corrector does to the frozen corpus today. */
const PINNED_TOKENS_CHANGED = 397;
const PINNED_OCCURRENCES_CHANGED = 43_269;

const CLITICS = [
  "وبال",
  "فبال",
  "وكال",
  "وعال",
  "ولل",
  "فلل",
  "بال",
  "كال",
  "فال",
  "وال",
  "عال",
  "لل",
  "ال",
  "و",
  "ف",
  "ب",
  "ك",
  "ل",
];

const DIGIT = /[0-9٠-٩۰-۹]/;

export function runPhoenixCrmDictationCorpusTests() {
  const fixture = JSON.parse(readFileSync(FIXTURE_PATH, "utf8")) as Fixture;
  const tokens = Object.entries(fixture.tokens);

  assert.ok(
    tokens.length > 1000,
    `the fixture holds ${tokens.length} words — far too few to measure anything, so it was truncated or regenerated against the wrong corpus`,
  );

  // ── The fixture is words and counts, and stays that way ───────────────────────────────────────
  // This is the privacy guard, and it is mechanical because the file is regenerated by a script
  // that reads a clinical record. A token with a space in it is a phrase; a long one is a sentence.
  for (const [token] of tokens) {
    assert.doesNotMatch(
      token,
      /\s/,
      `"${token}" contains whitespace, so it is a phrase rather than a word — the fixture must never carry comment text out of the database`,
    );
    assert.ok(
      token.length <= 40,
      `"${token}" is ${token.length} characters, which is a sentence and not a word — the fixture must never carry comment text out of the database`,
    );
  }

  // ── What the corrector does to the whole corpus ───────────────────────────────────────────────
  let tokensChanged = 0;
  let occurrencesChanged = 0;
  const changes: { from: string; to: string; hits: number }[] = [];

  for (const [token, hits] of tokens) {
    const result = correctDictatedProducts(token);
    if (result.text === token) continue;
    tokensChanged += 1;
    occurrencesChanged += hits;
    changes.push({ from: token, to: result.text, hits });
  }

  // ── The refusals, checked against the corpus rather than against examples ─────────────────────
  // A competitor's drug turned into ours is the one failure with no honest recovery, so it is
  // asserted over every word in the corpus and not just the handful anyone thought to list.
  const competitors = new Set(COMPETITOR_TERMS.map((term) => normalizeArabic(term.toLowerCase())));
  for (const [token, hits] of tokens) {
    const folded = normalizeArabic(token.toLowerCase());
    const readings = [folded, ...CLITICS.filter((c) => folded.startsWith(c)).map((c) => folded.slice(c.length))];
    if (!readings.some((reading) => competitors.has(reading))) continue;
    assert.equal(
      correctDictatedProducts(token).text,
      token,
      `"${token}" (${hits} real comments) is another company's product or a molecule and must come back exactly as written — rewriting it into a Phoenix brand puts a sale in a clinical note that never happened`,
    );
  }

  // A dose is not a spelling mistake. Correcting the letters deletes the strength, which is the
  // part that says which of two things the rep meant.
  for (const [token, hits] of tokens) {
    if (!DIGIT.test(token)) continue;
    assert.equal(
      correctDictatedProducts(token).text,
      token,
      `"${token}" (${hits} real comments) carries a strength and must come back untouched — the matcher compares letters, so correcting it would silently drop the dose`,
    );
  }

  // ── Nothing but a product name can ever come out ──────────────────────────────────────────────
  // The strongest invariant here, and the one that does not need re-pinning: whatever the corrector
  // replaces a word with, the replacement is a canonical product name, optionally still wearing the
  // prefix the rep wrote. It cannot emit a variant spelling, a half-corrected word, or anything
  // else — so a bug in the matcher can leave text uncorrected, never garbled.
  const canonical = new Set(PRODUCT_VOCABULARY.flatMap((entry) => [entry.arabic, entry.latin]));
  for (const change of changes) {
    const name = [...canonical].find((product) => change.to.endsWith(product));
    assert.ok(
      name,
      `"${change.from}" became "${change.to}", which is not a canonical product name — the corrector must only ever emit a name from the vocabulary`,
    );
    const prefix = change.to.slice(0, change.to.length - name.length);
    assert.ok(
      prefix === "" || CLITICS.includes(prefix),
      `"${change.from}" became "${change.to}", whose prefix "${prefix}" is not a clitic — the rep's own grammar is put back exactly as written or not at all`,
    );
  }

  assert.equal(
    tokensChanged,
    PINNED_TOKENS_CHANGED,
    `the corrector now changes ${tokensChanged} of the corpus's words rather than ${PINNED_TOKENS_CHANGED}. That is not automatically wrong — widening the vocabulary is supposed to move it — but it has to be LOOKED AT: run scripts/dictation-corrector-eval.ts, read what moved, and re-pin this number only once every new change is a word that should have changed`,
  );
  assert.equal(
    occurrencesChanged,
    PINNED_OCCURRENCES_CHANGED,
    `the corrector now rewrites ${occurrencesChanged.toLocaleString()} real occurrences rather than ${PINNED_OCCURRENCES_CHANGED.toLocaleString()} — read the evaluation report before re-pinning it`,
  );

  // ── The vocabulary is still doing its job ─────────────────────────────────────────────────────
  // The pins above go red if the vocabulary is gutted, but they go red for every other reason too.
  // These say out loud what the feature is for, so a green suite means it still works.
  for (const [spoken, expected, why] of [
    ["الجوماسين", "الجواميسين", "the corpus's single largest misspelling, 1,663 comments"],
    ["سانجكو", "ساجنكو", "the largest miss the recall measurement found"],
    ["saginkgo", "Saginko", "the spelling the field prefers, folded to the one the product table uses"],
    ["التببوفورتين", "التيبوفورتين", "an ordinary typo behind the article, with the article put back"],
  ] as const) {
    assert.equal(correctDictatedProducts(spoken).text, expected, `${spoken} → ${expected}: ${why}`);
  }

  // And the words it must never touch, which are the most common words in the corpus.
  for (const [ordinary, hits] of [
    ["الدكتور", 24658],
    ["التأكيد", 794],
    ["الماكس", 507],
    ["الجينكو", 533],
    ["الليفو", 394],
    ["اكتوبر", 68],
  ] as const) {
    assert.equal(
      correctDictatedProducts(ordinary).text,
      ordinary,
      `"${ordinary}" appears ${hits.toLocaleString()} times in the corpus as an ordinary word, a molecule or a tier — turning it into a brand name would put a product in thousands of comments that never mentioned one`,
    );
  }
}
