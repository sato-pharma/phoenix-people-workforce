export function escapeEmailHtml(value: string | number | null | undefined) {
  return String(value ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function escapeAndIsolate(value: string | number | null | undefined) {
  return bidiIsolate(escapeEmailHtml(value));
}

export function renderEmailParagraphs(value: string | null | undefined) {
  return String(value ?? "")
    .replace(/\r\n/g, "\n")
    .split(/\n{2,}/)
    .map((part) => part.trim())
    .filter(Boolean)
    .map((paragraph) => {
      const lines = paragraph
        .split("\n")
        .map((line) => bidiIsolate(escapeEmailHtml(line.trim())))
        .filter(Boolean)
        .join("<br />");

      return `<p class="phoenix-text" style="margin:0 0 14px;${bodyTextStyle};font-family:Arial,Helvetica,sans-serif;font-size:15px;font-weight:400;line-height:1.75">${lines}</p>`;
    })
    .join("");
}

export function renderPhoenixMetadataTable(rows: PhoenixEmailMetadataRow[] | undefined) {
  const cleanRows = (rows ?? []).filter((row) => String(row.value ?? "").trim());
  if (cleanRows.length === 0) return "";

  // Premium zebra-striped details table. Row striping is applied inline (email clients
  // routinely drop <style>, and almost none honor :nth-child), with a matching class so the
  // dark-mode blocks in the document <style> can re-tint the stripes. Wrapped in a rounded,
  // bordered shell for a document-grade look.
  const zebraBase = "#ffffff";
  const zebraAlt = "#f1f5f9";
  return `
    <table class="phoenix-metadata" role="presentation" width="100%" cellspacing="0" cellpadding="0" border="0" style="margin:24px 0 0;width:100%;border-collapse:separate;border-spacing:0;border:1px solid #cbd5e1;border-radius:12px;overflow:hidden;box-shadow:0 6px 16px rgba(15,23,42,0.04);mso-table-lspace:0pt;mso-table-rspace:0pt">
      ${cleanRows
        .map((row, index) => {
          const isAlt = index % 2 === 1;
          const rowBg = isAlt ? zebraAlt : zebraBase;
          const isLast = index === cleanRows.length - 1;
          const cellBorder = isLast ? "" : "border-bottom:1px solid #e2e8f0;";
          const altClass = isAlt ? " phoenix-metadata-row-alt" : "";
          return `
            <tr class="phoenix-metadata-row${altClass}" bgcolor="${rowBg}">
              <td class="phoenix-muted phoenix-metadata-cell${altClass}" bgcolor="${rowBg}" style="padding:16px 20px;background:${rowBg};${cellBorder}${mutedTextStyle};font-family:Arial,Helvetica,sans-serif;font-size:12px;font-weight:800;letter-spacing:0.05em;text-transform:uppercase;line-height:1.5;vertical-align:middle;white-space:nowrap">${escapeAndIsolate(row.label)}</td>
              <td class="phoenix-text phoenix-metadata-cell${altClass}" bgcolor="${rowBg}" style="padding:16px 20px;background:${rowBg};${cellBorder}${bodyTextStyle};font-family:Arial,Helvetica,sans-serif;font-size:15px;font-weight:900;line-height:1.5;text-align:right;vertical-align:middle;unicode-bidi:isolate">${escapeAndIsolate(row.value)}</td>
            </tr>`;
        })
        .join("")}
    </table>`;
}

/** Plain-text projection of renderPhoenixMetadataTable, for the text part of an email (or a
 * {{...Text}} template token standing in for a {{...}} pre-rendered HTML table token). */
export function renderPhoenixMetadataTableText(rows: PhoenixEmailMetadataRow[] | undefined) {
  return (rows ?? [])
    .filter((row) => String(row.value ?? "").trim())
    .map((row) => `${row.label}: ${row.value}`)
    .join("\n");
}

function renderPhoenixAction(action: PhoenixEmailAction | undefined) {
  if (!action) return "";

  const toneClass = action.tone === "danger" ? "danger" : action.tone === "secondary" ? "secondary" : "primary";
  const toneStyle =
    action.tone === "danger"
      ? "border-color:#fecaca;background:#fff1f2;color:#be123c;-webkit-text-fill-color:#be123c"
      : action.tone === "secondary"
        ? "border-color:#cbd5e1;background:#f8fafc;color:#0f172a;-webkit-text-fill-color:#0f172a"
        : "border-color:#fed7aa;background:#fff7ed;color:#ea580c;-webkit-text-fill-color:#ea580c";

  return `<a class="phoenix-action phoenix-action-${toneClass}" href="${escapeEmailHtml(action.href)}" style="display:inline-block;margin-top:22px;border:1px solid;${toneStyle};border-radius:10px;font-family:Arial,Helvetica,sans-serif;font-size:14px;font-weight:900;line-height:1.2;text-decoration:none;padding:12px 18px">${escapeEmailHtml(action.label)}</a>`;
}

