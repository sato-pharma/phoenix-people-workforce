export function renderPhoenixEmailText(input: {
  action?: PhoenixEmailAction;
  bodyText: string;
  closingText?: string;
  greeting?: string;
  metadataRows?: PhoenixEmailMetadataRow[];
  signatureTagline?: string;
  signatureName?: string;
  title: string;
}) {
  const signatureTagline = input.signatureTagline ?? phoenixEmailAutoGeneratedNote;
  const lines = [
    input.title,
    "",
    input.greeting ?? "",
    "",
    input.bodyText.trim(),
    "",
    ...(input.metadataRows ?? []).map((row) => `${row.label}: ${row.value ?? ""}`),
    input.action ? "" : "",
    input.action ? `${input.action.label}: ${input.action.href}` : "",
    input.closingText ? "" : "",
    input.closingText ?? "",
    "",
    "Best regards,",
    input.signatureName || systemIdentity.hrSignatureName,
    signatureTagline,
  ].filter((line, index, list) => line !== "" || list[index - 1] !== "");

  return lines.join("\n");
}
