function normalizeProfileImageKey(value: string | null | undefined) {
  return String(value ?? "")
    .trim()
    .toUpperCase()
    .replace(/[^A-Z0-9]/g, "");
}

export function employeeProfileImageForHrId(hrId: string | null | undefined) {
  const key = normalizeProfileImageKey(hrId);
  if (!key) return null;
  return employeeProfileImagesByKey[key] ?? null;
}
