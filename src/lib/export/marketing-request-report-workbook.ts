import ExcelJS from "exceljs";

import {
  buildCoverSheet,
  phoenixBandHeader,
  sanitizeSheetName,
  writeTable,
  type CellValue,
  type TableColumn,
} from "@/lib/export/phoenix-xlsx-style";
import {
  APPROVAL_COLUMNS,
  PHARMACY_COLUMNS,
  PRODUCT_COLUMNS,
  REQUEST_COLUMNS,
  approvalRowCells,
  cairoDateTime,
  pharmacyRowCells,
  productRowCells,
  requestRowCells,
  type FullReportRequest,
} from "@/lib/marketing-requests/request-report-columns";

// ─────────────────────────────────────────────────────────────────────────────
// The full Marketing Request workbook: the owner's 16-column template, widened to every field
// the system holds, plus one sheet per repeating child.
//
// Styling is the shared Phoenix kit (same band, palette and table writer as the ROI and Direct
// Orders workbooks) rather than a one-off look — the owner's rule is that a new surface matches
// its siblings exactly.
// ─────────────────────────────────────────────────────────────────────────────

const CONFIDENTIAL_NOTE =
  "CONFIDENTIAL — contains marketing spend, customer identities, GPS capture and the full approval "
  + "trail for every request. Internal distribution only.";

export type FullReportWorkbookMeta = {
  exportedByHrId: string;
  exportedByName: string;
  generatedAtIso: string;
  role: string;
};

function addSheet(
  workbook: ExcelJS.Workbook,
  name: string,
  title: string,
  subtitle: string,
  columns: TableColumn[],
  rows: CellValue[][],
  emptyNote: string,
) {
  const sheet = workbook.addWorksheet(sanitizeSheetName(name), { properties: { defaultColWidth: 16 } });
  phoenixBandHeader(sheet, Math.max(1, columns.length), title, subtitle);
  writeTable(sheet, 4, {
    columns,
    // A report that silently shows nothing reads as "there is no such data". Say which it is.
    note: rows.length === 0 ? emptyNote : undefined,
    rows,
    title: `${title} — ${rows.length} ${rows.length === 1 ? "row" : "rows"}`,
  });
  // Freeze the header so the 100+ columns stay readable while scrolling right.
  sheet.views = [{ state: "frozen", xSplit: 1, ySplit: 5 }];
  return sheet;
}

export async function buildMarketingRequestReportWorkbook(
  requests: FullReportRequest[],
  meta: FullReportWorkbookMeta,
): Promise<ArrayBuffer> {
  const workbook = new ExcelJS.Workbook();

  const totalCost = requests.reduce((sum, request) => sum + (request.estimatedCost ?? 0), 0);
  const totalRoi = requests.reduce((sum, request) => sum + (request.expectedRoiValue ?? 0), 0);

  buildCoverSheet(workbook, {
    confidentialNote: CONFIDENTIAL_NOTE,
    rows: [
      ["Scope", "Requests raised in Phoenix only — the historical xlsx import is excluded"],
      ["Requests", String(requests.length)],
      ["Total amount (EGP)", totalCost.toLocaleString("en-US", { minimumFractionDigits: 2 })],
      ["Total estimated ROI (EGP)", totalRoi.toLocaleString("en-US", { minimumFractionDigits: 2 })],
      ["Product lines", String(requests.reduce((sum, request) => sum + request.products.length, 0))],
      ["Approval steps", String(requests.reduce((sum, request) => sum + request.approvalSteps.length, 0))],
      ["Pharmacy links", String(requests.reduce((sum, request) => sum + request.pharmacies.length, 0))],
      ["Month / Week basis", "Request date · week runs Sunday → Thursday · W1 is the week containing the 1st"],
      ["Times shown in", "Africa/Cairo"],
      ["Generated at", cairoDateTime(meta.generatedAtIso) ?? meta.generatedAtIso],
      ["Generated by", `${meta.exportedByName} (${meta.exportedByHrId}) — ${meta.role}`],
    ],
    subtitle: "Every field the system holds about each request",
    title: "Marketing Request Report",
  });

  addSheet(
    workbook,
    "Requests",
    "Requests",
    "The template's 16 columns first, then every remaining field",
    REQUEST_COLUMNS,
    requests.map((request, index) => requestRowCells(request, index + 1)),
    "No request has been raised in Phoenix yet.",
  );

  addSheet(
    workbook,
    "Products",
    "Products",
    "What each request's estimated ROI is actually built from",
    PRODUCT_COLUMNS,
    requests.flatMap((request) => request.products.map((product) => productRowCells(request, product))),
    "No products are attached to these requests.",
  );

  addSheet(
    workbook,
    "Approval trail",
    "Approval trail",
    "Every step, who it was assigned to, who decided it and when",
    APPROVAL_COLUMNS,
    requests.flatMap((request) => request.approvalSteps.map((step) => approvalRowCells(request, step))),
    "No approval steps exist for these requests.",
  );

  addSheet(
    workbook,
    "Pharmacies",
    "Pharmacies",
    "The pharmacies each request's sales will be tracked through",
    PHARMACY_COLUMNS,
    requests.flatMap((request) => request.pharmacies.map((pharmacy) => pharmacyRowCells(request, pharmacy))),
    "No pharmacy is linked to these requests.",
  );

  return workbook.xlsx.writeBuffer() as unknown as Promise<ArrayBuffer>;
}
